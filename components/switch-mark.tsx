'use client';

import { motion, useReducedMotion } from 'motion/react';

/**
 * Светлая плашка «вы находитесь здесь», которая переезжает, а не
 * перескакивает.
 *
 * Один и тот же приём во всех переключателях продукта: период на
 * сводке, роль в боковой колонке, разделы на телефоне, вход и
 * регистрация в окне. В приложении это `matchedGeometryEffect`, здесь —
 * `layoutId`: плашка отрисована только под выбранным пунктом, и когда
 * выбранным становится сосед, движок сам ведёт её из старого места в
 * новое.
 *
 * Зачем вообще. Переключатель без движения не говорит, ЧТО именно
 * изменилось: плашка гаснет слева и загорается справа, и глаз читает
 * это как две разные вспышки. Переехавшая плашка — одна и та же вещь,
 * сменившая место, и связь между «я нажал сюда» и «выбралось это»
 * получается без чтения.
 *
 * Пружина без отскока: переключатель периода жмут по сорок раз за
 * смену, и качающаяся плашка на сороковом нажатии уже раздражает.
 * Отскок остаётся тому, что видят раз в день.
 *
 * `id` должен быть свой у каждой группы: две группы с одним
 * идентификатором начнут перебрасывать плашку между собой через весь
 * экран.
 */
export function SwitchMark({
  id,
  radius = 7,
  fill = 'var(--on-board)',
}: {
  id: string;
  radius?: number;
  fill?: string;
}) {
  const still = useReducedMotion();

  return (
    <motion.span
      layoutId={id}
      aria-hidden
      className="absolute inset-0"
      style={{ background: fill, borderRadius: radius, zIndex: 0 }}
      transition={
        still
          ? { duration: 0 }
          : /* 320 мс — верх бюджета для элемента управления: длиннее, и
               интерфейс начинает казаться медленнее пальца. */
            { type: 'spring', duration: 0.32, bounce: 0 }
      }
    />
  );
}
