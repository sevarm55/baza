'use client';

import Image from 'next/image';
import { motion, useReducedMotion } from 'motion/react';

/**
 * Мойщик в правой половине первого экрана.
 *
 * Один кадр, а не двадцать пять. Раньше здесь лежала раскадровка из
 * видео, и робот поворачивался за курсором; приём работал, но исходник
 * был снят с шумом и мылом, и на большом экране это видно в первую
 * очередь. Одна отрисовка в полном качестве честнее любой механики,
 * которую она обслуживает.
 *
 * Кадр пришёл уже без фона, со своим альфа-каналом. Проверен замером,
 * а не на глаз: просвет между ног прозрачен (там раньше и оставался
 * лист), полупрозрачных точек по контуру одиннадцать с половиной тысяч,
 * и светлых среди них семь сотен — это губка и бутыль, а не ободок от
 * белой подложки. Обрезано по альфе, под полностью прозрачным цвет
 * обнулён: без этого он лезет наружу при сжатии.
 *
 * Движение осталось, но своё: робот едва заметно дышит. Это не
 * взаимодействие, а признак жизни — кадр без него на светлой теме
 * читается наклейкой.
 *
 * Указателя слой не ловит. На телефоне робот стоит в нижней трети и
 * чуть уходит за правый край: заголовку он там не мешает, потому что
 * место под него отведено отступом снизу у самого заголовка
 * (`app/page.tsx`), а не отвоёвано у него внахлёст. Высота задана в
 * `svh`, а не в точках: на телефоне высота кадра и есть высота экрана,
 * и доля от неё держится одинаково на любом аппарате.
 */

/** Размер файла. Нужен `next/image`, чтобы не считать раскладку заново. */
const W = 976;
const H = 1501;

export function Robot({ alt }: { alt: string }) {
  const still = useReducedMotion();

  return (
    <motion.div
      className={[
        'pointer-events-none absolute z-[5] aspect-[976/1501]',
        /* Телефон: низ кадра, лёгкий выход за правый край. */
        'right-[-4%] bottom-0 h-[40svh]',
        /* Планшет и шире: высота задаётся краями, ширину считает пропорция. */
        'md:top-[12%] md:right-[3%] md:bottom-[4%] md:h-auto',
      ].join(' ')}
      animate={still ? undefined : { y: [0, -9, 0] }}
      transition={{ duration: 7, repeat: Infinity, ease: 'easeInOut' }}
    >
      <Image
        src="/hero/robot.webp"
        alt={alt}
        width={W}
        height={H}
        priority
        className="size-full object-contain object-bottom"
      />
    </motion.div>
  );
}
