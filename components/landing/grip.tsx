'use client';

import { motion, useReducedMotion } from 'motion/react';

/**
 * Мойщик, ухватившийся за верхний край карточки записи.
 *
 * Кромки в картинке нет: пальцы держатся за то, что нарисует не рендер,
 * а браузер — за настоящую границу соседнего узла. Поэтому размер и
 * положение задаются только в долях от неё, и на любом экране хват
 * остаётся хватом.
 *
 * Выезжает он не «из-под» карточки, и это не придирка. Карточка почти
 * прозрачна (белое в три с половиной процента на тёмном листе), и робот,
 * ползущий за ней, просвечивал бы насквозь. Вместо этого у него своя
 * коробка с обрезкой по нижнему краю: он поднимается внутри неё, а всё,
 * что ниже, отсечено. Снаружи это читается так, будто он вылез из-за
 * края.
 *
 * Коробка опущена на несколько точек ниже границы, чтобы пальцы легли
 * ПОВЕРХ неё. Без этого они заканчиваются ровно на линии, и вместо
 * хвата выходит наклейка, приставленная сверху.
 *
 * Стоит справа: слева на карточке номер машины, и место там занято.
 */

/** Пропорция файла. Нужна коробке, пока картинка ещё не загрузилась. */
const RATIO = '900 / 631';

export function Grip({ src, active }: { src: string; active: boolean }) {
  const still = useReducedMotion();

  return (
    <div
      aria-hidden
      className="pointer-events-none absolute right-[6%] bottom-full w-[96px] translate-y-[6px] overflow-hidden sm:w-[140px] sm:translate-y-[9px] lg:w-[176px]"
      style={{ aspectRatio: RATIO }}
    >
      <motion.img
        src={src}
        alt=""
        width={900}
        height={631}
        className="h-auto w-full"
        initial={{ y: '100%' }}
        animate={{ y: still || active ? '0%' : '100%' }}
        transition={
          still ? { duration: 0 } : { type: 'spring', stiffness: 120, damping: 18, mass: 0.9 }
        }
      />
    </div>
  );
}
