'use client';

import { motion, useReducedMotion } from 'motion/react';

/**
 * Появление на первом экране: из расфокуса в резкость.
 *
 * Строка приходит смазанной и наводится на резкость, слегка поднимаясь.
 * Это не декоративный блюр, а имитация фокусировки объектива: кадр
 * наверху снят камерой, и текст в нём ведёт себя как снятый, а не как
 * подставленный.
 *
 * Компонент нарочно крошечный и клиентский, а страница остаётся
 * серверной. Текст приходит внутрь как `children`, то есть отрисован на
 * сервере и лежит в разметке: анимация оборачивает содержимое, а не
 * заменяет его.
 *
 * Задержки заданы числом, а не `staggerChildren`: марка живёт в шапке, а
 * заголовок с подписью — в теле экрана, это разные ветки разметки, и
 * общего родителя у них нет. Числа подобраны так, чтобы читалось как
 * одна волна сверху вниз.
 *
 * Easing не линейный (правило дизайн-системы) — `[0.16, 1, 0.3, 1]`:
 * быстрый старт и долгий вынос, на нём расфокус читается наводкой, а не
 * рывком. Пружину здесь не берём: она проскакивает мимо цели, а резкость
 * не может «перелететь».
 *
 * При «уменьшении движения» компонент отдаёт содержимое как есть, без
 * обёртки и без единого кадра анимации.
 */
export function Reveal({
  children,
  className,
  delay = 0,
  blur = 12,
  y = 16,
}: {
  children: React.ReactNode;
  className?: string;
  delay?: number;
  /** Начальный расфокус в точках. */
  blur?: number;
  /** Подъём в точках. */
  y?: number;
}) {
  const still = useReducedMotion();

  if (still) return <div className={className}>{children}</div>;

  return (
    <motion.div
      /* Метка для страховки без скриптов: стартовое состояние анимации —
         нулевая прозрачность, и если JS не доехал, заголовок первого
         экрана исчез бы совсем. Правило в `app/layout.tsx` под
         `<noscript>` возвращает слою нормальный вид. */
      data-reveal
      className={className}
      initial={{ opacity: 0, y, filter: `blur(${blur}px)` }}
      animate={{ opacity: 1, y: 0, filter: 'blur(0px)' }}
      transition={{ duration: 0.9, delay, ease: [0.16, 1, 0.3, 1] }}
    >
      {children}
    </motion.div>
  );
}
