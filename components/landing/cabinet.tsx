import Image from 'next/image';

import type { Dict } from '@/lib/i18n';

import { Screen } from './screen';
import { Words } from './words';

/**
 * Кабинет владельца. Ответ на предыдущую секцию.
 *
 * До сих пор витрина показывала продукт только моими руками: карточка
 * записи и живая лента нарисованы разметкой, а не сняты. Здесь стоит
 * НАСТОЯЩИЙ экран настоящего кабинета — тот самый, за который просят
 * пятнадцать тысяч в месяц. На витрине для дела это единственное, что
 * по-настоящему убеждает.
 *
 * Снято отладочным протоколом Chrome в двойной плотности: панель
 * предпросмотра отдаёт максимум восемьсот точек по ширине, и снимок
 * кабинета на большом экране был бы мылом. Данные — демо-мойка
 * «Ավտոլվացում Արշակունյաց» из локальной базы, наполненная тем же
 * `infra/showcase-topup.sql`, что держит витринную мойку на проде. Отсюда
 * и подпись «демо» в углу: числа настоящие по сходимости, но мойка не
 * чужая, а наша.
 *
 * Кадров шесть: три языка на две ширины. Продукт трёхъязычный, и
 * армянский кабинет на русской витрине читался бы чужим снимком.
 *
 * Две ширины — не подгонка одного снимка, а два разных экрана продукта.
 * У кабинета своя раскладка для телефона: крупная прибыль, плитки,
 * плавающая полоса разделов. Десктопное окно, сжатое до трёхсот
 * девяноста точек, превращается в серое пятно, по которому нельзя
 * прочесть ни одной цифры, — а секция ровно про то, что цифры видно.
 *
 * Оба снимка ленивые и спрятаны противоположными правилами ширины:
 * браузер не грузит то, чего не показывает.
 *
 * За снимком горит тот же свет, что в первом экране, и приходит он
 * сверху (`screen.tsx`). Белое окно кабинета на тёмном листе иначе висит
 * вырезанным прямоугольником, ни с чем на странице не связанным.
 *
 * Низ кадра растворяется в листе. Снимок обрезан на середине содержимого
 * — иначе пришлось бы либо сжимать весь кабинет до нечитаемого, либо
 * рвать его по случайной линии. Растворение делает обрез намеренным:
 * окно в то, что продолжается за краем.
 */

/** Размеры файлов. Одинаковые на все языки — снимки сняты одним заходом. */
const WIDE = { w: 2400, h: 1467 };
const PHONE = { w: 780, h: 1560 };

export function Cabinet({ t }: { t: Dict }) {
  const l = t.landing.cabinet;

  return (
    <section
      id="cabinet"
      aria-labelledby="cabinet-title"
      className="scroll-mt-16 bg-[var(--landing-bg)]"
    >
      <div className="mx-auto w-full max-w-[1360px] px-5 py-20 md:px-10 md:py-28">
        <Words
          id="cabinet-title"
          text={l.title}
          className="font-wordmark max-w-[18ch] text-[26px] leading-[1.12] tracking-[-0.01em] uppercase md:text-[36px]"
        />

        <p className="mt-5 max-w-[54ch] text-[15px] leading-relaxed text-muted-foreground md:mt-6 md:text-base">
          {l.lead}
        </p>

        <div className="mt-12 md:mt-16">
          <Screen>
            {/* Подпись «демо» стоит НАД кадром, а не на нём. Числа
                сходятся между собой, но мойка наша, и молчать об этом
                нельзя — та же подпись висит над живой лентой в третьей
                секции. На самом снимке ей места нет: сверху у продукта
                свои органы (филиал, уведомления, аватар), снизу кадр
                растворяется. */}
            <div className="mb-3 flex justify-end">
              <span className="text-2xs rounded-lg border border-border px-2 py-1 font-medium tracking-wider text-muted-foreground uppercase">
                {t.landing.live.demo}
              </span>
            </div>

            {/* Низ кадра растворяется в листе.
 
                Сделано маской, а не заливкой поверх. Заливка лежит внутри
                рамки и её нижнюю грань не закрывает: содержимое уже ушло
                в цвет листа, а поперёк кадра оставалась светлая полоска —
                та самая грань. Маска гасит элемент целиком, вместе с
                рамкой и тенью, и полоске взяться неоткуда.
 
                Обрезать снимок по этой линии нельзя: кабинет продолжается
                за краем, и растворение говорит об этом честнее ровного
                среза. */}
            <div
              className="overflow-hidden rounded-[10px] border border-border shadow-[0_40px_90px_-50px_rgba(26,18,14,0.55)] md:rounded-[14px] dark:shadow-[0_40px_90px_-50px_rgba(0,0,0,0.9)]"
              style={{
                maskImage: 'linear-gradient(to bottom, #000 78%, transparent 100%)',
                WebkitMaskImage: 'linear-gradient(to bottom, #000 78%, transparent 100%)',
              }}
            >
              <Image
                src={`/cabinet/phone-${t.locale}.webp`}
                alt={l.title}
                width={PHONE.w}
                height={PHONE.h}
                className="block h-auto w-full md:hidden"
                sizes="(max-width: 767px) 100vw, 1px"
              />
              <Image
                src={`/cabinet/owner-${t.locale}.webp`}
                alt={l.title}
                width={WIDE.w}
                height={WIDE.h}
                className="hidden h-auto w-full md:block"
                sizes="(min-width: 1400px) 1280px, 100vw"
              />
            </div>
          </Screen>
        </div>
      </div>
    </section>
  );
}
