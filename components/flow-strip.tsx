import type { ReactNode } from 'react';
import { NumericText } from '@/components/numeric-text';

/**
 * Полоса-цепочка: откуда пришло, куда ушло, что осталось.
 *
 * Заменяет собой и ряд отдельных плиток, и «финансовую цепочку» под
 * ними. В задании они шли двумя рядами — сначала четыре карточки
 * `Հասույթ / Աշխատավարձ / Ծախսեր / Ձեզ մնում է`, следом те же четыре
 * числа со стрелками, — и это те же данные два раза подряд, около ста
 * двадцати пикселей первого экрана на повтор. Глаз при этом не находит
 * разницы между рядами и ищет её, вместо того чтобы читать.
 *
 * Здесь ряд KPI сам и есть цепочка: между звеньями стоят «−» и «=»,
 * знаки настоящие, а не рисованные стрелки. Отношение чисел читается
 * без единого слова объяснения, а место под графиком остаётся.
 *
 * Звено «осталось» тёмное. Это единственный итог на экране, ради
 * которого владелец кабинет и открывает, и единственное место, где
 * цвет здесь несёт смысл, а не украшает: остальные звенья белые.
 */

export type Link = {
  label: string;
  value: string;
  /** знак перед звеном: чем оно связано с предыдущим */
  sign?: '−' | '+' | '=';
  /** подпись под числом — доля, база сравнения */
  note?: string;
  /** итог: тёмная заливка, крупнее прочих */
  strong?: boolean;
  /** звено открывает список за собой; без него это просто число */
  onOpen?: () => void;
  /**
   * Знак звена и его тон.
   *
   * Значок здесь не украшение: полоса из четырёх чисел читается слева
   * направо словами, а по знаку нужное звено находится раньше, чем
   * прочитана подпись. Тон при этом несёт смысл, а не раскрашивает:
   * деньги пришли — фиолетовый, ушли — янтарный, доля людей —
   * бирюзовый, итог — лайм на тёмной плите. Пятого тона в продукте
   * нет, и пятое значение придумывать нельзя.
   */
  icon?: ReactNode;
  tone?: 'violet' | 'teal' | 'amber' | 'lime';
};

export function FlowStrip({ links }: { links: Link[] }) {
  return (
    <div className="flow">
      {links.map((l) => {
        /* Нажимаемое звено — настоящая кнопка, а не div с обработчиком:
           так оно попадает в обход по клавиатуре и объявляется читалкой
           экрана само, без единого атрибута руками. */
        const Tag = l.onOpen ? 'button' : 'div';
        return (
        <Tag
          key={l.label}
          type={l.onOpen ? 'button' : undefined}
          onClick={l.onOpen}
          className={`flow-link${l.strong ? ' flow-link-strong' : ''}${l.onOpen ? ' flow-link-open' : ''}`}
        >
          {/* Знак живёт в шве между звеньями, а не внутри карточки:
              он про связь, а не про число. На узком экране, где
              звенья складываются в столбец, он уезжает влево и
              продолжает читаться. */}
          {l.sign && (
            <span className="flow-sign" aria-hidden>
              {l.sign}
            </span>
          )}
          {l.icon && (
            <span className="flow-mark" data-tone={l.tone ?? 'violet'} aria-hidden>
              {l.icon}
            </span>
          )}
          <span className="flow-label">{l.label}</span>
          <span className="num flow-value">
            <NumericText>{l.value}</NumericText>
          </span>
          {l.note && <span className="flow-note num">{l.note}</span>}
        </Tag>
        );
      })}
    </div>
  );
}
