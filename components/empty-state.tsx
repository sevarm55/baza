import type { ReactNode } from 'react';

/**
 * Пусто — это ответ, а не отсутствие ответа.
 *
 * «Դեռ տվյալներ չկան» посреди прибора сообщает ровно одно: здесь ничего
 * нет. Человек, открывший раздел впервые, из этой строки не узнаёт ни
 * что здесь появится, ни откуда оно берётся, ни что сделать, чтобы
 * появилось, — и уходит, решив, что раздел сломан или не для него.
 *
 * Поэтому у пустого места три части, и третья не всегда нужна: что это
 * за список, откуда в нём берутся строки и — если строку заводит сам
 * владелец — кнопка, которая её заводит. Там, где строки появляются
 * сами (клиенты приезжают, записи делает мойщик), кнопки нет: обещать
 * действие, которого не существует, хуже, чем промолчать.
 */
export function EmptyState({
  title,
  note,
  action,
}: {
  title: string;
  /** откуда здесь берутся строки — одно предложение, не абзац */
  note?: string;
  /** что сделать прямо сейчас; пусто, когда делать нечего */
  action?: ReactNode;
}) {
  return (
    <div className="empty">
      <p className="empty-title">{title}</p>
      {note && <p className="empty-note">{note}</p>}
      {action && <div className="mt-3.5">{action}</div>}
    </div>
  );
}
