'use client';

import { usePathname } from 'next/navigation';
import type { ReactNode } from 'react';

/**
 * Появление содержимого при переходе между разделами.
 *
 * Оболочка кабинета — колонка разделов, шапка, вкладки внизу — при
 * переходе остаётся на месте: она уже нарисована и уже нажимается,
 * гасить её ради загрузки соседней страницы незачем. Меняется только
 * рабочая область, и она обязана не подставляться встык.
 *
 * Шесть пикселей и четверть секунды. Не слайд на пол-экрана: это
 * рабочий инструмент, который открывают сорок раз за смену, а не
 * презентация продукта. Движение здесь отвечает на один вопрос — «то,
 * что я вижу, уже новое?» — и на этом заканчивается.
 *
 * Ключом стоит адрес: без него React считает содержимое тем же самым
 * узлом и анимация не проигрывается вовсе. При «Уменьшении движения»
 * остаётся одна прозрачность — это решает CSS класса `.async-in`.
 */
export function PageFade({ children }: { children: ReactNode }) {
  const path = usePathname();
  return (
    <div key={path} className="async-in">
      {children}
    </div>
  );
}
