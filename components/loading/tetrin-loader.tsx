'use client';

import { motion, useReducedMotion } from 'motion/react';

import { E, T } from '@/lib/motion';

/**
 * Фирменный загрузчик.
 *
 * Четыре столбика — то, из чего собран весь продукт: они в графике дня,
 * в профиле недели, в значке вкладки, на плитках щита. Пока приложение
 * думает, оно показывает ту же фигуру, которой показывает деньги, и это
 * единственная причина, по которой загрузчик здесь свой, а не кружок.
 *
 * Что делает фигура за оборот:
 *
 *   волна  →  сходятся  →  складываются 2×2  →  вдох  →  расходятся
 *
 * Волна говорит «идёт счёт»: столбики поднимаются по очереди, как
 * растёт столбик выручки. Складывание в квадрат — момент, ради которого
 * всё и затевалось: четыре одинаковые детали на секунду становятся
 * одним знаком, и знак этот больше нигде не встречается, поэтому
 * запоминается. Вдох ставит точку, расхождение возвращает в начало.
 *
 * Ни один кадр не крутится вокруг центра. Вращение — это чужой язык:
 * так выглядит каждый второй индикатор в вебе, и фигура, которая
 * крутится, перестаёт быть чьей-то.
 *
 * Оборот кончается там же, где начался: последний кадр совпадает с
 * первым по всем трём величинам, поэтому шва между оборотами не видно.
 * Двигаются только `transform` и `opacity` — обе идут мимо раскладки, и
 * на слабом телефоне анимация не роняет кадры.
 *
 * При «Уменьшении движения» фигура стоит лесенкой и вместо неё дышит
 * прозрачность: настройка запрещает движение, а не признак работы.
 */

/** Доли оборота, на которых стоят опорные кадры. */
const TIMES = [0, 0.08, 0.16, 0.24, 0.32, 0.44, 0.6, 0.7, 0.8, 0.92, 1];

/** Кривая на каждом промежутке между опорными кадрами. */
const EASE = [
  'easeInOut', // волна: столбик 1
  'easeInOut', // столбик 2
  'easeInOut', // столбик 3
  'easeInOut', // столбик 4
  E.spring, //   сходятся к центру, с еле заметным перелётом
  E.soft, //     складываются в квадрат
  'easeOut', //  вдох
  'easeInOut', // выдох
  E.spring, //   расходятся обратно в ряд
  'linear', //   пауза перед новым оборотом
] as const;

/** Шаг между столбиками в ряду, в долях высоты фигуры. */
const PITCH = 0.3;
/** Ширина столбика, в долях высоты фигуры. */
const BAR = 0.17;

/**
 * Насколько ряд сжимается к центру перед складыванием.
 *
 * Не теснее: при 0.46 шаг между столбиками (0.138 высоты) становится
 * меньше их ширины (0.17), четыре детали сливаются в один
 * прямоугольник, и вместо «сошлись» видно «пропали». Здесь между ними
 * остаётся щель, и фигура читается сжатым рядом, а не пятном.
 */
const COMPRESS = 0.72;

/** Куда столбик уезжает по горизонтали в сомкнутом квадрате. */
const GRID_X = 0.115;
/** И по вертикали. */
const GRID_Y = 0.155;

/**
 * Высота столбика на кадрах волны.
 *
 * Столбик с номером `i` вытягивается на своём кадре, соседние поднимаются
 * на треть. Отсюда бегущая волна вместо четырёх одновременных морганий.
 */
function wave(i: number) {
  return [0, 1, 2, 3, 4].map((k) => {
    const d = Math.abs(k - (i + 1));
    const lift = d === 0 ? 1 : d === 1 ? 0.34 : 0;
    return 0.4 + 0.6 * lift;
  });
}

export function TetrinLoader({
  size = 30,
  tone = 'var(--accent-fill)',
  className = '',
  label,
}: {
  /** Высота фигуры в пикселях. Ширина считается от неё. */
  size?: number;
  /** Цвет столбиков. */
  tone?: string;
  className?: string;
  /** Что скажет чтец экрана. Пусто — фигура для него не существует. */
  label?: string;
}) {
  const still = useReducedMotion();
  const w = size * BAR;

  return (
    <span
      className={`tetrin-loader ${className}`}
      style={{ width: size * 1.24, height: size }}
      role={label ? 'status' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      <motion.span
        className="tetrin-loader-stage"
        animate={still ? undefined : { scale: [1, 1, 1, 1.055, 1, 1, 1] }}
        transition={
          still
            ? undefined
            : {
                duration: T.loader,
                times: [0, 0.44, 0.6, 0.7, 0.8, 0.92, 1],
                ease: 'easeInOut',
                repeat: Infinity,
              }
        }
      >
        {[0, 1, 2, 3].map((i) => {
          const rowX = (i - 1.5) * PITCH * size;
          const gridX = (i < 2 ? -GRID_X : GRID_X) * size;
          const gridY = (i % 2 === 0 ? -GRID_Y : GRID_Y) * size;
          const w0 = wave(i);

          /* Ряд складывается пополам, а не перетасовывается: левая пара
             уходит влево, правая вправо. Иначе третий столбик пролетает
             сквозь второй, и вместо складывания видно свалку. */
          return (
            <motion.span
              key={i}
              className="tetrin-loader-bar"
              style={{
                width: w,
                height: size,
                borderRadius: w / 2,
                background: tone,
              }}
              initial={false}
              animate={
                still
                  ? { scaleY: 0.42 + 0.58 * (i / 3), opacity: [1, 0.42, 1] }
                  : {
                      x: [...Array(5).fill(rowX), rowX * COMPRESS, gridX, gridX, gridX, rowX, rowX],
                      y: [0, 0, 0, 0, 0, 0, gridY, gridY, gridY, 0, 0],
                      scaleY: [...w0, 0.56, 0.26, 0.26, 0.26, w0[0], w0[0]],
                    }
              }
              transition={
                still
                  ? { duration: 2.2, repeat: Infinity, ease: 'easeInOut' }
                  : { duration: T.loader, times: TIMES, ease: EASE as never, repeat: Infinity }
              }
            />
          );
        })}
      </motion.span>
    </span>
  );
}
