'use client';

import { AnimatePresence, motion } from 'motion/react';

import { T } from '@/lib/motion';
import { TetrinLoader } from './tetrin-loader';

/**
 * Заслонка на весь экран.
 *
 * Единственный уровень загрузки, который отбирает у человека всё сразу,
 * и потому единственный, у которого есть список допустимых поводов:
 * запуск приложения, восстановление сессии, проверка замка. Ничего из
 * того, что касается одной страницы или одного прибора, здесь не
 * появляется — для этого есть скелет раздела и занятая кнопка.
 *
 * На вебе такого повода нет вовсе: оболочка кабинета приезжает уже
 * собранной с сервера, и показывать поверх неё фиолетовый экран значит
 * прятать то, что уже готово. Компонент живёт здесь ради приложений и
 * ради того единственного случая, когда веб всё же перезапускает себя
 * целиком.
 *
 * Фон не плоский. Плоская заливка на весь экран читается как ошибка
 * загрузки стилей; здесь из центра идёт очень слабое свечение, а к
 * краям грейп темнеет. Разница между центром и краем меньше десяти
 * процентов светлоты: заставка обязана быть фоном для фигуры, а не
 * рекламным экраном.
 */
export function FullScreenLoader({
  show = true,
  /** «Синхронизируем данные…» — только если это правда та операция */
  note,
}: {
  show?: boolean;
  note?: string;
}) {
  return (
    <AnimatePresence>
      {show && (
        <motion.div
          className="tetrin-splash"
          initial={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          transition={{ duration: T.normal }}
          role="status"
          aria-live="polite"
        >
          <TetrinLoader size={40} tone="var(--tone-lime)" />
          {/* Подписи по умолчанию нет. «Загрузка…» под движущейся
              фигурой не добавляет ни одного факта, а занимает строку и
              задаёт вопрос «а сколько ещё». Текст появляется только
              тогда, когда есть что сказать про конкретную операцию, и
              никогда не показывает процент: сервер его не присылает, а
              нарисованный процент врёт. */}
          {note && <p className="tetrin-splash-note">{note}</p>}
        </motion.div>
      )}
    </AnimatePresence>
  );
}
