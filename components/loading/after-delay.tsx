'use client';

import type { ReactNode } from 'react';

import { LOADING_DELAY } from '@/lib/motion';
import { useDelayedFlag } from './use-delayed';

/**
 * Показать скелет, только если переход затянулся.
 *
 * Next подставляет `loading.tsx` в тот же кадр, в котором началась
 * навигация, — то есть и на разделы, которые открываются за девяносто
 * миллисекунд. Человек видит вспышку серых прямоугольников и решает, что
 * страница дрогнула: это хуже, чем если бы не было ничего.
 *
 * Порог тот же, что у всех остальных состояний ожидания, и держит его
 * тот же хук. Данные при этом не придерживаются ни на миллисекунду:
 * порог откладывает показ загрузки, а не показ страницы. Пока он идёт,
 * на экране остаётся прежний раздел, а подсвеченная вкладка уже говорит,
 * что нажатие принято.
 */
export function AfterDelay({ ms = LOADING_DELAY, children }: { ms?: number; children: ReactNode }) {
  const shown = useDelayedFlag(true, ms);
  return shown ? <>{children}</> : null;
}
