import { isStaging, stagingLabel } from '@/lib/staging';

/**
 * Метка тестового стенда.
 *
 * На боевом сайте не отрисовывается вовсе: `null` вместо пустого узла,
 * чтобы в разметке не было даже следа, по которому стенд можно принять
 * за бой с выключенной меткой.
 *
 * Форма выбрана от обратного — от того, куда её нельзя ставить. Верх
 * занят шапкой с филиалом, низ полосой разделов, и любая плашка в углу
 * на каком-нибудь экране легла бы на кнопку. Рамка по периметру окна не
 * занимает ни одной точки содержимого: она рисуется поверх, клики
 * проходят насквозь (`pointer-events-none`), а вёрстка под ней не знает,
 * что она есть.
 *
 * Второе достоинство рамки важнее первого: рамки вокруг всего окна в
 * продукте нет нигде и никогда. Плашку со словом можно спутать с частью
 * интерфейса, обведённое окно — нельзя.
 *
 * Слово показывается только на широком экране. На телефоне для него нет
 * безопасного места: сверху чёлка и часы, снизу домашняя черта, а по
 * бокам в повороте те самые сорок семь точек. Рамки там достаточно, а
 * кто открыл стенд с телефона, знает об этом и без подписи.
 *
 * `z-50` — выше шапки (`z-30`) и полосы разделов (`z-40`), то есть выше
 * всего, что остаётся на экране постоянно. Модальные листы рисуются в
 * портале в конце разметки и с тем же `z-50` ложатся поверх нижней
 * грани рамки. Так и надо: лист занимает не весь экран, верхняя грань
 * из-под него видна, а рамка, перечёркивающая диалог, выглядела бы
 * поломкой вёрстки.
 */
export function StagingBadge() {
  if (!isStaging()) return null;

  const label = stagingLabel();

  return (
    <div aria-hidden className="pointer-events-none fixed inset-0 z-50 select-none">
      <div className="absolute inset-0 border-2 border-m-grape" />
      <span
        className="absolute top-0 left-1/2 hidden -translate-x-1/2 bg-m-grape px-2 py-0.5 text-[10px] font-bold tracking-[0.2em] text-m-lime md:block"
        style={{ borderRadius: '0 0 var(--radius-chip) var(--radius-chip)' }}
      >
        {label}
      </span>
    </div>
  );
}
