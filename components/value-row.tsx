import type { ReactNode } from 'react';

/**
 * Строка «что — сколько», которую только читают.
 *
 * Половина непонятности профиля была именно здесь: телефон и роль
 * лежали в таких же серых прямоугольниках, что и поля ввода, и человек
 * щёлкал по своему номеру, пытаясь его исправить. Читаемое значение —
 * это текст: без заливки, без рамки, без радиуса. Поле ввода рядом
 * выглядит иначе намеренно (см. `.field`), и разница видна раньше, чем
 * прочитана подпись.
 *
 * Стопка таких строк оборачивается в `.rows`: волосяная линия между
 * ними — та же, что в списках кабинета.
 */
export function ValueRow({
  label,
  value,
  mono,
}: {
  label: string;
  value: ReactNode;
  /** цифры в столбик: телефон, сумма, дата */
  mono?: boolean;
}) {
  return (
    <div className="value-row">
      <span className="value-row-label">{label}</span>
      <span className={`value-row-value${mono ? ' num' : ''}`}>{value}</span>
    </div>
  );
}
