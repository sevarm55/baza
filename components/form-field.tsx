import type { ReactNode } from 'react';

/**
 * Поле с постоянной подписью.
 *
 * Подпись здесь обязательна и стоит НАД полем, а не внутри него
 * подсказкой. Подсказка исчезает на первой набранной букве — и человек,
 * вернувшийся к недописанной форме, видит ряд заполненных строк, ни у
 * одной из которых не написано, что в ней лежит. Проверить набранное
 * можно только стерев его.
 *
 * Подпись связана с полем через `htmlFor`, а не обёрткой `<label>`
 * вокруг всего: внутри формы бывает своя форма (название бизнеса — это
 * отдельный `<form>` с кнопкой), а форму в подпись заворачивать нельзя —
 * поле внутри неё перестаёт быть подписанным.
 *
 * Отсюда единственное требование к вызывающему: тот же `id` обязан
 * стоять на самом поле.
 */
export function FormField({
  id,
  label,
  hint,
  error,
  children,
}: {
  /** тот же id, что у поля внутри: он и связывает подпись с вводом */
  id: string;
  label: string;
  /** что произойдёт после сохранения; не повтор подписи другими словами */
  hint?: ReactNode;
  error?: string | null;
  children: ReactNode;
}) {
  return (
    <div className="grid gap-1.5">
      <label className="label" htmlFor={id}>
        {label}
      </label>
      {children}
      {hint !== undefined && <p className="field-hint">{hint}</p>}
      {/* Ошибка не цветом одним: рядом с красным стоит текст, который
          называет причину. Цвет читают не все. */}
      {error && <p className="alert">{error}</p>}
    </div>
  );
}
