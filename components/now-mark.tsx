'use client';

import { useEffect, useState } from 'react';

/**
 * «Сейчас · 19:26» — признак того, что числа на экране живые.
 *
 * Приём приехал с витрины, где он объяснял показ: точка горит, время
 * идёт, значит панель считает, а не показывает вчерашний снимок. В
 * кабинете он объясняет то же самое, только там это правда буквально —
 * сводка пересчитывается на каждом открытии страницы.
 *
 * Время БИЗНЕСА, а не смотрящего. Владелец в отпуске за границей
 * открывает кабинет и видит час своей мойки: сутки на мойке считаются
 * по её поясу, и «сейчас» обязано совпадать с тем «сейчас», по которому
 * закрывается день.
 *
 * Первое значение приходит с сервера и рисуется как есть — иначе при
 * первой отрисовке в разметке была бы пустота, а в браузере время, и
 * React ругался бы на расхождение. Дальше его подменяет часовой ход:
 * раз в полминуты, потому что показаны только часы и минуты, и чаще
 * незачем.
 */
export function NowMark({
  initial,
  timezone,
  label,
}: {
  /** час бизнеса на момент отрисовки страницы */
  initial: string;
  timezone: string;
  /** слово «сейчас» на языке смотрящего */
  label: string;
}) {
  const [time, setTime] = useState(initial);

  useEffect(() => {
    /* Первый пересчёт — по таймеру, а не сразу: сразу означало бы
       поставить состояние прямо в эффекте и вызвать вторую отрисовку
       ради значения, которое почти всегда совпадает с серверным. */
    const id = setInterval(() => {
      setTime(
        new Intl.DateTimeFormat('en-GB', {
          timeZone: timezone,
          hour: '2-digit',
          minute: '2-digit',
          hourCycle: 'h23',
        }).format(new Date()),
      );
    }, 30_000);
    return () => clearInterval(id);
  }, [timezone]);

  return (
    <span className="now-mark">
      <i aria-hidden />
      {label}
      <span className="num">{time}</span>
    </span>
  );
}
