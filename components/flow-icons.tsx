/**
 * Знаки поводов.
 *
 * Нарисованы здесь, а не взяты картинками: у продукта один контур —
 * линия 1.5 по сетке 16, — и он должен тянуться, краситься темой и
 * оставаться резким на любом экране. Картинка ничего из этого не умеет.
 *
 * Набор маленький, и стал он таким не сразу. Здесь лежало двенадцать
 * значков — по одному на каждое звено полосы показаний: машина, приход,
 * расход, кошелёк, люди, звезда, ценник, пистолет мойщика. Полосы больше
 * нет ни на одной странице кабинета: её заменила пара «плита и
 * слагаемые», где значок ничего не добавлял — подпись под числом и так
 * стоит в двух словах от него.
 *
 * Остались двое, и обоим есть что делать: повод в колокольчике
 * находится по значку раньше, чем прочитан заголовок, потому что поводов
 * всего два вида и они не похожи.
 */
const S = {
  fill: 'none',
  stroke: 'currentColor',
  strokeWidth: 1.5,
  strokeLinecap: 'round',
  strokeLinejoin: 'round',
} as const;

function I({ children }: { children: React.ReactNode }) {
  return (
    <svg viewBox="0 0 16 16" className="size-4" aria-hidden {...S}>
      {children}
    </svg>
  );
}

