/**
 * С чем сравнили и на сколько разошлось.
 *
 * Три вещи в одной строке: имя базы с датами, её сумма, разница со знаком.
 * Порядок такой, потому что менее сенсационное число идёт первым — иначе
 * разница читается сама по себе и кажется больше, чем есть.
 *
 * В драмах, а не в процентах. Процент от маленькой базы врёт: у мойки
 * пятнадцать-сорок машин в день, и один корпоративный клиент на пять машин
 * даёт «+30 %». Абсолютную разницу как равноправный режим дают FreshBooks
 * («Amount Change»), QuickBooks («$ change»), Luzmo («Absolute change») и
 * Square («the percent or value change») — ни один не требует процента.
 *
 * «К прошлому периоду» без дат не сообщает ничего: человек должен видеть,
 * что сравнили первое-седьмое августа с первым-седьмым июля.
 */
export function Compare({
  label,
  base,
  diff,
  baseCount,
  money,
}: {
  /** имя базы с датами: «Հուլիսի 1–7» или «Մեկ շաբաթ առաջ այս ժամին» */
  label: string;
  base: number;
  diff: number;
  /** сколько записей было в базе */
  baseCount: number;
  money: (n: number) => string;
}) {
  /* Молчим, когда сравнивать не с чем: бизнес завёлся на этой неделе, и
     прошлого месяца у него не было. «+100 % от нуля» — это не новость, а
     артефакт деления. Так же поступает Metricool («no equivalent previous
     period») и GitLab, который в этом случае пишет «n/a». */
  if (baseCount === 0) return null;

  // разница меньше сотни драмов — строка займёт место и ничего не скажет
  if (Math.abs(diff) < 100) return null;

  return (
    <div className="mt-1.5 text-[13.5px] text-muted">
      {label}
      <span className="num"> {money(base)}</span>
      <span className="text-faint"> · </span>
      {/* Знак и слово, а не цвет: WCAG 1.4.1 запрещает передавать смысл
          одним цветом, а этот экран смотрят на мокром телефоне под солнцем,
          где оттенок пропадает первым. */}
      <span className={`num font-semibold ${diff > 0 ? 'text-good' : 'text-warn'}`}>
        {diff > 0 ? '+' : '−'}
        {money(Math.abs(diff))}
      </span>
    </div>
  );
}
