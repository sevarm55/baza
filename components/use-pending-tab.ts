'use client';

import { useState } from 'react';

/**
 * Подсветка переезжает на нажатую вкладку сразу, не дожидаясь сервера.
 *
 * Страницы владельца динамические: их нельзя отдать заранее, поэтому
 * до ответа сервера ссылка ничем не отзывается. На телефоне это полсекунды
 * мёртвого экрана — человек решает, что промахнулся, жмёт ещё раз и уходит
 * уже не туда.
 *
 * Догадка живёт ровно до подтверждения: как только `current` пришёл новым,
 * она снимается прямо в рендере, и подсветкой снова управляет сервер.
 * Не эффектом — иначе кадр между ответом сервера и сбросом показал бы
 * подсвеченными сразу две вкладки. Если переход не состоялся — редирект,
 * отказ в правах, «назад» — `current` тоже сменится, и догадка отпадёт.
 */
export function usePendingTab<T extends string>(current: T) {
  const [clicked, setClicked] = useState<T | null>(null);
  const [seen, setSeen] = useState<T>(current);

  if (seen !== current) {
    setSeen(current);
    setClicked(null);
  }

  const active = seen === current ? (clicked ?? current) : current;

  return {
    /** Вкладка, которую видит человек: нажатая, а не обязательно открытая. */
    active,
    /** Нажата одна, открыта пока другая — страница в пути. */
    pending: active !== current,
    select: setClicked,
  };
}
