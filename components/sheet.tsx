'use client';

import { useEffect, useRef, type ReactNode } from 'react';
import { IconClose } from '@/components/icons';

/**
 * Окно правки поверх страницы.
 *
 * На нативном `<dialog>`, а не на своём слое: ловушка фокуса, Escape,
 * затемнение и верхний слой достаются бесплатно и работают правильно —
 * своя реализация всего этого обычно ошибается на клавиатуре.
 *
 * Три части, а не одна куча.
 *
 * Раньше окно было просто серым прямоугольником с полями внутри: имя,
 * цена, во всю ширину лаймовая кнопка, а под ней, отдельной строкой и
 * непонятно куда прижатое, — «удалить». Кричала не та кнопка, а найти
 * можно было только методом чтения сверху вниз.
 *
 * Теперь у окна есть шапка (что правим), тело (чем правим) и подвал
 * (что с этим сделать). Волосяные линии между ними — не украшение: они
 * говорят, что подвал не продолжение формы, а её итог, и что кнопки в
 * нём относятся ко всему окну, а не к последнему полю. Действия стоят
 * по краям подвала: убрать — слева и тихо, сохранить — справа, там,
 * где рука заканчивает читать.
 *
 * `footer` отдельным свойством, потому что кнопка «сохранить»
 * принадлежит форме в теле, а стоит вне её. Связывает их атрибут
 * `form` по идентификатору — так это и задумано в HTML, и не приходится
 * ни вкладывать формы друг в друга, ни поднимать всю форму в подвал.
 */
export function Sheet({
  open,
  onClose,
  title,
  subtitle,
  side,
  footer,
  children,
}: {
  open: boolean;
  onClose: () => void;
  title: string;
  /** вторая строка шапки: чей это телефон, за какое число расход */
  subtitle?: string;
  /**
   * Панелью справа, а не окном по центру.
   *
   * Там, где правят строку длинного списка, окно по центру закрывает
   * собой сам список: человек теряет из виду, что он открыл и что
   * стоит вокруг. Панель приходит от края, список остаётся на месте —
   * так же, как карточка машины у клиентов.
   */
  side?: boolean;
  /** действия окна: слева убрать, справа сохранить */
  footer?: ReactNode;
  children: ReactNode;
}) {
  const ref = useRef<HTMLDialogElement>(null);
  const head = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const dialog = ref.current;
    if (!dialog) return;

    if (open && !dialog.open) {
      /* `showModal` сам наводится на первое поле. На телефоне это
         мгновенно выбрасывает клавиатуру поверх окна, которое человек
         ещё не прочитал, поэтому цель фокуса ставится заранее — на
         заголовок. */
      head.current?.setAttribute('autofocus', '');
      dialog.showModal();
    }
    if (!open && dialog.open) dialog.close();
  }, [open]);

  /* Каркас задан прямо здесь, а не только классом. Окно живёт в верхнем
     слое браузера, и если стиль по какой-то причине не доехал (первая
     отрисовка, старый кэш, сборка в момент правки), `<dialog>`
     разворачивается в браузерный дефолт: белая коробка во всю ширину,
     поля навылет, кнопка через весь экран. Класс остаётся — он несёт
     тона полотна, линии и анимацию, — но размер и центр держатся сами.

     `inset: 0` вместе с `margin: auto` — это и есть центр: четыре нуля
     прижимают окно ко всем краям сразу, а автополя делят остаток
     поровну. Без них браузер ставит окно по своему умолчанию, и в
     верхнем слое оно оказывается где угодно, только не посередине.

     Поля тут нет вовсе: его несут части окна по отдельности, иначе
     линия между шапкой и телом не дойдёт до краёв.

     Чего здесь больше нет — так это `display`. Он единственный из всего
     каркаса меняется от состояния: закрытое окно обязано пропасть, а не
     висеть невидимой плитой поверх страницы и перехватывать касания.
     Разметка задать этого не может — она не знает про `[open]`, — и
     задавала «всегда flex», перебивая и стиль, и правило браузера.
     Теперь `display` целиком за классом, а запасной путь остаётся
     рабочим и без него: без стилей браузер сам покажет открытое окно и
     спрячет закрытое, а шапка, тело и подвал сложатся столбиком, потому
     что они блоки. */
  return (
    <dialog
      ref={ref}
      className={side ? 'drawer' : 'sheet'}
      /* Каркас панели держит её собственный класс: он и так задаёт край,
         ширину и выезд, а повтор этого в разметке спорил бы с ним. */
      style={
        side
          ? undefined
          : {
              position: 'fixed',
              inset: 0,
              margin: 'auto',
              width: 'min(440px, calc(100vw - 2rem))',
              maxHeight: 'calc(100dvh - 3rem)',
              overflow: 'hidden',
              padding: 0,
              borderRadius: 'var(--radius-card)',
              background: 'var(--board-surface)',
              color: 'var(--on-board)',
            }
      }
      onCancel={(e) => {
        e.preventDefault();
        onClose();
      }}
      // клик по затемнению: цель события — сам <dialog>, а не панель
      onClick={(e) => {
        if (e.target === ref.current) onClose();
      }}
      onClose={onClose}
    >
      <div ref={head} tabIndex={-1} className="sheet-head">
        <div className="min-w-0">
          <h2 className="truncate text-[16px] leading-tight font-semibold tracking-[-0.015em]">
            {title}
          </h2>
          {subtitle && <p className="num sheet-sub">{subtitle}</p>}
        </div>
        <button type="button" className="sheet-x" onClick={onClose} aria-label="Փակել">
          <IconClose className="size-4" />
        </button>
      </div>

      <div className="sheet-body">{children}</div>

      {footer && <div className="sheet-foot">{footer}</div>}
    </dialog>
  );
}
