import type { ReactNode } from 'react';

/**
 * Заголовок раздела.
 *
 * Слева — где мы, справа — чем здесь управляют: период, кнопка,
 * выгрузка. На телефоне управление сползает под заголовок, потому что
 * рядом с ним ему не хватает ширины.
 *
 * На компьютере заголовок не дублирует подсветку в меню, а держит
 * верх страницы: без него полотно начинается сразу с цифры, и глазу
 * не за что зацепиться, когда раздел меняют.
 */
export function PageHead({
  title,
  meta,
  standalone,
  children,
}: {
  title: string;
  /** тихая строка под заголовком: даты периода, счётчик, пояснение */
  meta?: ReactNode;
  /**
   * Раздела нет в полосе вкладок — заголовок нужен и на телефоне.
   *
   * У остальных он там лишний: подсвеченная вкладка называет раздел тем
   * же словом строкой выше, и «Այսօր» оказывалось на экране трижды
   * подряд — вкладка, заголовок и выбранный период.
   */
  standalone?: boolean;
  /** управление справа */
  children?: ReactNode;
}) {
  return (
    <div className="page-head">
      <div className="min-w-0">
        <h1 className={`page-title ${standalone ? '' : 'hidden lg:block'}`}>{title}</h1>
        {meta !== undefined && (
          <div className="mt-0.5 text-[13.5px]" style={{ color: 'var(--board-muted)' }}>
            {meta}
          </div>
        )}
      </div>
      {children}
    </div>
  );
}
