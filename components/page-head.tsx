import type { ReactNode } from 'react';

/**
 * Заголовок раздела.
 *
 * Слева — где мы, справа — чем здесь управляют: период, кнопка,
 * выгрузка. На телефоне управление сползает под заголовок, потому что
 * рядом с ним ему не хватает ширины.
 *
 * На компьютере заголовок не дублирует подсветку в меню, а держит
 * верх страницы: без него полотно начинается сразу с цифры, и глазу
 * не за что зацепиться, когда раздел меняют.
 */
export function PageHead({
  title,
  meta,
  children,
}: {
  title: string;
  /** тихая строка под заголовком: даты периода, счётчик, пояснение */
  meta?: ReactNode;
  /** управление справа */
  children?: ReactNode;
}) {
  return (
    <div className="page-head">
      <div className="min-w-0">
        {/* Заголовок виден и на телефоне.

            Здесь стоял признак `standalone`: у разделов из полосы вкладок
            заголовок на телефоне прятался, потому что подсвеченная вкладка
            называла раздел тем же словом строкой выше, и «Այսօր»
            оказывалось на экране трижды подряд.

            Полосы вкладок больше нет — разделы уехали в выдвижную колонку
            вместе с переходом на боковое меню, — и вместе с ней исчезло
            единственное место, где раздел назывался. На телефоне страница
            начиналась пояснением без заголовка: «Управление услугами,
            ценами и условиями работы» под пустотой, и понять, где ты,
            можно было только открыв меню. */}
        <h1 className="page-title">{title}</h1>
        {meta !== undefined && (
          <div className="mt-0.5 text-[13.5px]" style={{ color: 'var(--board-muted)' }}>
            {meta}
          </div>
        )}
      </div>
      {children}
    </div>
  );
}
