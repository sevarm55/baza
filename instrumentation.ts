/**
 * Выполняется один раз при старте сервера, до первого запроса.
 *
 * Миграции здесь, а не лениво при первом обращении к базе: иначе их
 * оплачивает первый посетитель, а если что-то пойдёт не так — увидит
 * ошибку вместо страницы. Плюс до первого запроса можно вообще не знать,
 * что схема не накатилась: страница входа в базу не ходит.
 */
export async function register() {
  // хук зовётся и для edge-рантайма, где базы нет
  if (process.env.NEXT_RUNTIME !== 'nodejs') return;
  if (process.env.MIGRATE_ON_START !== '1') return;

  const { ensureDb } = await import('./lib/db/ready');
  await ensureDb();
  console.log('миграции применены');
}
