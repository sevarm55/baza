package com.sevarm.tetr.core.money

/**
 * Совместная мойка: одна машина, несколько исполнителей.
 *
 * Здесь только арифметика — ни сети, ни экранов. Причина та же, что у
 * прайса по классам: считать деньги обязано одно место. Сервер делит фонд
 * при записи, экран мойщика показывает будущую долю до нажатия кнопки,
 * кабинет владельца объясняет уже посчитанное. Три ответа на один вопрос,
 * и разойтись им негде только пока формула одна.
 *
 * Порт `lib/crew.ts` слово в слово. Расхождение означало бы, что мойщик
 * видит перед нажатием одну сумму, а вечером в ведомости другую, — а
 * узнать свой заработок из чужой бумажки значит решить, что тебя
 * обсчитали.
 *
 * Лежит не в `i18n` рядом с `Money`, хотя речь о деньгах: там деньги
 * зависят от языка — разделитель разрядов, знак валюты, склонение. Доля
 * от языка не зависит ни в чём.
 *
 * ПРАВИЛО ЦЕЛИКОМ:
 *
 *   моет один   → фонд = цена × ЛИЧНЫЙ процент этого человека;
 *   моют двое+  → фонд = цена × ОБЩИЙ процент команды, делится поровну.
 *
 * Общий процент — это не «по столько каждому». Пятьдесят процентов на
 * троих означают пять тысяч с десятитысячной машины на всех, а не
 * пятнадцать: иначе зарплатный фонд одной машины перевалил бы за её цену
 * на четвёртом участнике.
 */
object Crew {

    /** Сколько человек максимум может мыть одну машину. */
    const val MAX = 8

    /**
     * Зарплатный фонд машины.
     *
     * Округление вниз — то же самое, которым продукт считает долю
     * одиночного мойщика с самого начала. Второй способ округлять означал
     * бы, что совместная мойка на одного человека даёт не ту сумму, что
     * одиночная, при одинаковом проценте.
     */
    fun pool(price: Int, percent: Int): Int = price * percent / 100

    /**
     * Разделить фонд между участниками.
     *
     * ОСТАТОК НЕ ТЕРЯЕТСЯ И НЕ ПРИДУМЫВАЕТСЯ. Пять тысяч на троих — это не
     * «по 1 666,67»: денег в драмах дробных не бывает, а сумма долей
     * обязана до последней единицы совпасть с фондом. Иначе зарплатная
     * ведомость не сходится с расходом на зарплату, и расхождение
     * всплывает у владельца ровно там, где продукт обещал порядок.
     *
     * Поэтому 5 000 на троих дают 1 667 + 1 667 + 1 666. Лишние единицы
     * уходят первым по порядку, а первый — автор записи: если уж кому-то
     * достаётся на драм больше, пусть это будет тот, кто взял на себя
     * оформление.
     */
    fun split(pool: Int, people: Int): List<Int> {
        if (people <= 0) return emptyList()
        val base = pool / people
        val extra = pool - base * people
        return List(people) { i -> base + if (i < extra) 1 else 0 }
    }

    /** Сколько получит каждый и по какой ставке. */
    data class Result(val percent: Int, val pool: Int, val shares: List<Int>)

    /**
     * Всё, что нужно и серверу, и обоим экранам.
     *
     * `percent` возвращается наружу, потому что он и есть то, что уйдёт
     * снимком в запись: спрашивать «а какой процент применился» второй раз
     * было бы вторым источником правды для той же величины.
     */
    fun compute(
        price: Int,
        /** сколько человек мыли, считая автора записи */
        people: Int,
        /** личная ставка того, кто моет один */
        soloPercent: Int,
        /** общая ставка команды; null — совместная мойка не настроена */
        teamPercent: Int?,
    ): Result {
        val percent = if (people > 1) (teamPercent ?: 0) else soloPercent
        val pool = pool(price, percent)
        return Result(percent, pool, split(pool, people))
    }
}
