package com.sevarm.tetr.core.phone

/**
 * Код страны при вводе номера.
 *
 * ЭТО НЕ ПРОВЕРКА НОМЕРА. Здесь только приставка к набранному и разбивка
 * на группы для глаза. Настоящий номер собирает и проверяет сервер
 * (`normalizePhone`, `isValidPhone` в `lib/phone.ts`) — тот же код и для
 * кабинета, и для приложений. Экранная строка ничего не гарантирует и
 * гарантировать не должна: клиент никогда не граница безопасности.
 *
 * Список повторяет `COUNTRIES` из `lib/phone.ts`. Повтор сознательный и
 * узкий: это подсказка для пальца, а не правило. Если страна появится на
 * сервере, а сюда её не добавят, номер всё равно примут — набранный с
 * плюсом он уйдёт как есть.
 */
data class Country(
    val code: String,
    val dial: String,
    val flag: String,
    /** Сколько цифр в национальной части. */
    val length: Int,
    /** Как выглядит здешний номер — подсказкой в пустом поле. */
    val example: String,
) {
    /**
     * Национальная часть из того, что набрали.
     *
     * Набранное вместе с кодом страны или с ведущим нулём — обычное дело:
     * человек диктует номер так, как привык, а вставленный из записной
     * книжки приходит с плюсом и кодом. Отрезаем то, что иначе уехало бы в
     * национальную часть и сделало номер длиннее настоящего.
     *
     * Обрезка по длине — ПОСЛЕ отсечения кода, а не до. Обратный порядок и
     * был ошибкой: «+374 77 000 001» превращалось в «37477000» прямо во
     * время набора, потому что восемь знаков кончались раньше, чем
     * начинался сам номер.
     */
    fun national(typed: String): String {
        var digits = typed.filter { it.isDigit() }

        if (digits.length > length) {
            digits = when {
                digits.startsWith(dial) -> digits.drop(dial.length)
                digits.startsWith("0") -> digits.drop(1)
                else -> digits
            }
        }
        return digits.take(length)
    }

    /** Собрать то, что уйдёт на сервер. Он всё равно нормализует заново. */
    fun e164(typed: String): String = "+$dial${national(typed)}"
}

object Countries {
    val all: List<Country> = listOf(
        Country("AM", "374", "🇦🇲", 8, "77 123 456"),
        Country("RU", "7", "🇷🇺", 10, "912 345 67 89"),
        Country("GE", "995", "🇬🇪", 9, "555 123 456"),
        Country("AE", "971", "🇦🇪", 9, "50 123 4567"),
        Country("US", "1", "🇺🇸", 10, "415 555 0123"),
    )

    val default: Country = all[0]

    /**
     * Угадать страну по сохранённому номеру.
     *
     * Нужно ровно там, где номер подставляется сам — при возврате к форме
     * после неудачного быстрого входа: без этого армянский номер оказался
     * бы в поле с кодом другой страны, и человек не понял бы, почему его
     * собственный номер не принимают.
     */
    fun guess(e164: String): Pair<Country, String> {
        val digits = e164.filter { it.isDigit() }
        val match = all
            .filter { digits.startsWith(it.dial) }
            .maxByOrNull { it.dial.length }
            ?: return default to default.national(digits)
        return match to match.national(digits)
    }
}
