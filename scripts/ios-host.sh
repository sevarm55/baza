#!/bin/sh
#
# Куда отладочная сборка ходит за данными.
#
# Адрес в схеме Xcode прибит гвоздями, а IP машины меняется от сети к
# сети: дома одна подсеть, в офисе другая, и приложение на телефоне
# молча упирается в «нет сети». Само оно найти компьютер не может: имя
# .local на офисном Wi-Fi не резолвится, а вписать адрес в сборку нечем —
# в проекте включена песочница пользовательских скриптов, и лезть в неё
# ради удобства значит ослаблять её всем.
#
# Поэтому одна команда вместо правки руками:
#
#     npm run ios:host
#
# Она берёт адрес того интерфейса, через который машина реально смотрит в
# сеть, находит запущенный сервер разработки и переписывает обе схемы —
# запуск и UI-тесты. После неё проект нужно открыть заново: Xcode держит
# .xcodeproj в памяти и старый адрес переживёт перегенерацию.
set -e

root=$(cd "$(dirname "$0")/.." && pwd)
project="$root/ios/project.yml"

# Интерфейс по умолчанию, а не en0: на маке с проводом и Wi-Fi сразу
# en0 может быть поднят и без адреса.
iface=$(route -n get default 2>/dev/null | awk '/interface:/{print $2}')
ip=$(ipconfig getifaddr "$iface" 2>/dev/null || true)

if [ -z "$ip" ]; then
  echo "сети нет: интерфейс по умолчанию без адреса" >&2
  exit 1
fi

# Порт того сервера, который сейчас слушает. 3100 первый: это обычный
# `npm run dev -- --port 3100`. Остальные — стенды из .claude/launch.json,
# они бывают подняты соседней сессией, и тогда 3100 занять нельзя.
port=""
for p in 3100 3311 3200 3105; do
  if lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1; then
    port=$p
    break
  fi
done

if [ -z "$port" ]; then
  port=3100
  echo "сервер разработки не запущен, ставлю порт $port"
fi

host="http://$ip:$port/api/v1/"

# Меняются обе строки TETR_API: запуск и UI-тесты. Прогон тестов по чужому
# адресу заводил бы машины живым мойкам.
/usr/bin/sed -i '' -E "s#value: http://[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+:[0-9]+/api/v1/#value: $host#g" "$project"

if ! grep -q "value: $host" "$project"; then
  echo "не нашёл, что менять: в $project нет строки с адресом вида http://IP:порт/api/v1/" >&2
  exit 1
fi

(cd "$root/ios" && xcodegen generate >/dev/null)

echo "адрес отладки: $host"
echo "закройте и откройте проект: open $root/ios/Tetr.xcodeproj"
