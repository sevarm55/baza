#!/bin/sh
# Демо-бизнес не должен пустеть.
#
# Сутки в продукте считаются по времени бизнеса и в полночь начинаются
# заново. Демо, наполненное один раз, назавтра показывает ревьюеру ноль
# машин и убыток размером с дневную долю аренды — ровно тот пустой экран,
# из-за которого отклоняют по Guideline 2.1. А ревью случается не тогда,
# когда его ждёшь.
#
# Раз в час: скрипт сам смотрит, сколько машин полагается к этому часу, и
# добавляет недостающие. Повторный запуск лишнего не сделает.
#
# Ходим прямо в контейнер базы: задача не зависит ни от DNS, ни от TLS,
# ни от соседнего Caddy, и наружу ничего не выходит.
set -e
docker exec -i bazis-postgres psql -U bazis -d bazis -q < /opt/bazis/infra/demo-topup.sql
