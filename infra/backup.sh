#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
#  Резервная копия базы. Раз в сутки из crontab.
#
#  Продукт устроен так, что записи не пропадают сами: заказ
#  отменяется мягко и остаётся в истории, работник отключается, а
#  не удаляется, просроченная подписка закрывает вход и не трогает
#  данные. Всё это защищает от ошибки внутри продукта.
#
#  Не защищает оно ровно от трёх вещей, и все три случаются молча:
#  владелец подтверждает «удалить бизнес» на телефоне, что сносит
#  мойку целиком по каскаду; кривая миграция уезжает на боевой при
#  MIGRATE_ON_START; умирает диск. После любой из них без копии
#  восстанавливать нечего.
#
#  Копия проверяется здесь же, а не «когда понадобится». Файл,
#  который не разжимается или не содержит записей, хуже отсутствия
#  копии: на него рассчитывают.
# ─────────────────────────────────────────────────────────────
set -euo pipefail

DIR=/opt/bazis/backups
CONTAINER=bazis-postgres
DB=bazis
USER=bazis
KEEP_DAYS=30

mkdir -p "$DIR"
# В дампе телефоны клиентов и работников, поэтому только root.
chmod 700 "$DIR"

STAMP="$(date -u +%Y-%m-%d)"
OUT="$DIR/bazis-$STAMP.sql.gz"
TMP="$OUT.part"

say() { echo "[$(date -u +%H:%M)] $*"; }
die() { echo "[$(date -u +%H:%M)] ОШИБКА: $*" >&2; rm -f "$TMP"; exit 1; }

# ── Сколько записей в живой базе прямо сейчас ──
#
# Это число нужно до снятия дампа: им проверяется сам дамп. Сверять
# копию с ней же самой бессмысленно, сверять надо с оригиналом.
live_rows() {
  docker exec "$CONTAINER" psql -U "$USER" -d "$DB" -tAc "select count(*) from $1" 2>/dev/null || echo "нет"
}

# ── Сколько строк таблицы реально легло в дамп ──
#
# pg_dump печатает `COPY public.orders (...) FROM stdin;`, потом
# строки, потом `\.` отдельной строкой. Пустая таблица даёт тот же
# заголовок, поэтому наличие COPY ничего не доказывает и считать
# приходится строки между ним и точкой.
dump_rows() {
  gzip -dc "$2" | awk -v t="$1" '
    $0 ~ "^COPY public\\." t " " { inside = 1; next }
    inside && $0 == "\\."       { inside = 0 }
    inside                       { n++ }
    END { print n + 0 }
  '
}

say "снимаю дамп базы $DB"
ORDERS_LIVE="$(live_rows orders)"
[ "$ORDERS_LIVE" = "нет" ] && die "база не отвечает, дамп не снимался"

docker exec "$CONTAINER" pg_dump -U "$USER" -d "$DB" --no-owner --no-privileges \
  | gzip -9 > "$TMP" || die "pg_dump не отработал"

# ── Проверка 1: файл вообще разжимается ──
gzip -t "$TMP" || die "архив битый"

# ── Проверка 2: на месте таблицы, в которых лежит работа мойки ──
#
# Список не для красоты: это ровно те таблицы, потерю которых
# владелец заметит. Схема без них восстановится, а мойка нет.
# Имена собираются одним проходом, а не поиском на каждую таблицу.
# Дело не в скорости: `gzip -dc | grep -q` при найденном совпадении
# закрывает поток, gzip получает SIGPIPE, а pipefail засчитывает это
# отказом. Проверка объявляла пропавшими ровно те таблицы, которые
# нашла, и пропускала только последние по алфавиту, до которых поток
# успевал дочитаться.
PRESENT="$(gzip -dc "$TMP" | sed -n 's/^COPY public\.\([a-z_]*\) .*/\1/p' | sort -u)"

MISSING=""
for t in tenants users accounts clients services orders order_shares shifts expenses passes; do
  echo "$PRESENT" | grep -qx "$t" || MISSING="$MISSING $t"
done
[ -n "$MISSING" ] && die "в дампе нет таблиц:$MISSING"

# ── Проверка 3: записей в копии столько же, сколько в базе ──
#
# Самая важная из трёх. Дамп, оборванный на середине, проходит и
# gzip -t, и проверку таблиц: обрыв случается после заголовка COPY.
ORDERS_DUMP="$(dump_rows orders "$TMP")"
if [ "$ORDERS_DUMP" -lt "$ORDERS_LIVE" ]; then
  die "в базе $ORDERS_LIVE записей, в копии $ORDERS_DUMP — дамп неполный"
fi

mv "$TMP" "$OUT"
chmod 600 "$OUT"
say "готово: $(basename "$OUT"), $(du -h "$OUT" | cut -f1), записей $ORDERS_DUMP"

# ── Уборка ──
#
# Копии за месяц посуточно, плюс первое число каждого месяца на год.
# Месячные переживают срок именно потому, что беда бывает тихой:
# запись, стёртую в июле, замечают в сентябре, и суточные копии к
# тому времени уже прокрутились.
if [ -d "$DIR" ]; then
  find "$DIR" -maxdepth 1 -type f -name 'bazis-????-??-??.sql.gz' \
    ! -name 'bazis-????-??-01.sql.gz' -mtime "+$KEEP_DAYS" -delete
  find "$DIR" -maxdepth 1 -type f -name 'bazis-????-??-01.sql.gz' -mtime +400 -delete
  find "$DIR" -maxdepth 1 -type f -name '*.part' -mtime +1 -delete
fi

say "в хранилище копий: $(ls -1 "$DIR"/bazis-*.sql.gz 2>/dev/null | wc -l | tr -d ' ') шт, $(du -sh "$DIR" | cut -f1)"
