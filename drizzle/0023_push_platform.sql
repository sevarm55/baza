-- Куда нести токен: Apple или Google.
--
-- До сих пор доставка была одна — APNs, — и платформу хранить было незачем.
-- С появлением Android токены двух видов лежат в одной таблице и внешне
-- неотличимы: строка как строка. Отправленный не туда токен FCM Apple
-- отвергает как BadDeviceToken, и чистка мёртвых удаляет его как
-- несуществующий — то есть Android замолкал бы навсегда после первой же
-- попытки.
--
-- Умолчание 'apns' — условие безопасности этой правки, а не вкусовщина:
-- все существующие строки эппловские, и умолчание оставляет их ровно
-- такими, какими они были. Без него живые iPhone получили бы пустую
-- платформу и замолчали бы сами.
ALTER TABLE "push_tokens" ADD COLUMN "platform" text DEFAULT 'apns' NOT NULL;
