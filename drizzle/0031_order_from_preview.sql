-- Отметка «машина записана в обучении, глазами работника».
--
-- В сценарии первого запуска владелец входит в режим работника и
-- записывает машину сам. Запись при этом настоящая — в этом и смысл: он
-- видит свою мойку, а не макет, и дальше сразу видит её же в сводке.
--
-- Но номер он вводит выдуманный, просто чтобы посмотреть, и эта машина
-- остаётся в дне навсегда: подмешивается в выручку, в средний чек и в
-- базу клиентов. Убрать её человеку негде — записи не удаляются, а
-- отмена оставляет серую строку в журнале.
--
-- Признак нужен ровно для одного: на финале обучения предложить убрать
-- эту машину одной кнопкой — и предложить именно её, а не настоящую,
-- которую владелец мог записать тем же вечером. Без пометки отличить их
-- нечем: обе сделаны работником в один день.
--
-- Значение по умолчанию `false`, поэтому все существующие записи
-- остаются такими, какие есть, и ни одна не становится кандидатом на
-- удаление задним числом.

ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "from_preview" boolean NOT NULL DEFAULT false;
