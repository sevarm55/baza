-- Доля участника в одной мойке.
--
-- `earned` — снимок, а не формула. Владелец завтра поменяет общий
-- процент, а послезавтра уволит человека; посчитанное вчера обязано
-- остаться посчитанным вчера. Тот же принцип, что у цены и процента в
-- самой записи.
--
-- `staff_id` гаснет в NULL вместе с человеком, а не уносит строку с
-- собой: деньги были начислены, и стирать их удалением людей нельзя.
-- Ровно так же ведёт себя `orders.staff_id`, и зарплатные запросы такие
-- строки уже умеют показывать безымянными.
CREATE TABLE IF NOT EXISTS "order_shares" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "tenant_id" uuid NOT NULL REFERENCES "tenants"("id") ON DELETE cascade,
  "order_id" uuid NOT NULL REFERENCES "orders"("id") ON DELETE cascade,
  "staff_id" uuid REFERENCES "users"("id") ON DELETE set null,
  "earned" integer NOT NULL,
  "sort" integer NOT NULL DEFAULT 0
);--> statement-breakpoint

