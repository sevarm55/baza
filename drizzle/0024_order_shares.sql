-- Перенос истории: у каждой существующей записи ровно один участник —
-- тот, кто её сделал, — и его доля равна тому, что продукт считал по ней
-- до сих пор, до драма.
--
-- Формула слово в слово та, что стоит в зарплатных запросах:
-- `floor(price * staff_percent / 100.0)`. Любое отличие здесь означало
-- бы, что у людей в день выката поехали суммы за прошлые дни.
--
-- Отменённые записи переносятся тоже. Отмена — признак записи
-- (`canceled_at`), и все запросы фильтруют по нему; выкинуть такие
-- строки здесь значило бы завести второй способ отменять, который
-- разойдётся с первым при первом же восстановлении.
INSERT INTO "order_shares" ("tenant_id", "order_id", "staff_id", "earned", "sort")
SELECT "tenant_id", "id", "staff_id", floor("price" * "staff_percent" / 100.0)::int, 0
FROM "orders"
ON CONFLICT DO NOTHING;
