-- Совместная мойка: одна машина — несколько исполнителей.
--
-- На мойке машину часто моют вдвоём-втроём. До сих пор продукт этого не
-- умел, и в жизни это записывали двумя способами, оба врущие: либо одной
-- машиной на одного человека (второй работал бесплатно), либо тремя
-- одинаковыми записями (машин втрое больше, выручка втрое больше).
--
-- ГЛАВНОЕ РЕШЕНИЕ: запись остаётся ОДНА. Меняется не она, а то, кому
-- принадлежит начисленное по ней. Раньше ответ был вшит в саму запись —
-- `orders.staff_id` плюс `orders.staff_percent`, — и другого получателя
-- у денег быть не могло. Теперь получатели лежат строками здесь.
--
-- ЧТО ТЕПЕРЬ ЗНАЧИТ `orders.staff_percent`. Процент, применённый к
-- ЗАПИСИ ЦЕЛИКОМ, то есть весь зарплатный фонд этой машины. У одиночной
-- мойки это, как и раньше, процент самого мойщика. У совместной — общий
-- процент команды. Инвариант один на оба случая:
--
--     floor(price * staff_percent / 100) = сумма долей участников
--
-- Благодаря ему всё, что считало зарплату бизнеса одной формулой по
-- записям — сводка, отчёты, выгрузка, прибыль, — продолжает считать
-- ровно то же самое и правится не было. Меняются только те запросы, что
-- отвечают на вопрос «сколько причитается ЭТОМУ человеку»: они уходят
-- отсюда, а не из `orders.staff_id`.
--
-- `orders.staff_id` при этом сохраняет прежний смысл и остаётся на
-- месте: это тот, КТО ВНЁС запись. У одиночной мойки он же и есть
-- исполнитель — поэтому старые данные не только не ломаются, но и не
-- требуют трактовки. У совместной автор записи — один из участников, и
-- владелец по нему видит, чьими руками запись появилась.

-- Общий процент команды. Один на бизнес, а не свой у каждого: иначе у
-- участников ОДНОЙ машины оказались бы разные ставки, и вопрос «сколько
-- стоила эта мойка» перестал бы иметь один ответ.
--
-- NULL — совместная мойка не настроена, и мойщику её не предлагают.
-- Умолчания здесь нет намеренно: любое число, поставленное за владельца,
-- было бы молчаливым решением о чужих деньгах.
