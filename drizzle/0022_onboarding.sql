-- Первый вход: приветствие и «Начало работы».
--
-- Две даты на участии человека в бизнесе — всё, что продукт помнит про
-- онбординг. Выполненность шагов не хранится нигде: она считается по
-- данным самого бизнеса (lib/onboarding.ts), потому что флаг рядом с
-- фактом рано или поздно начинает врать.
--
-- Существующие участия помечены прочитавшими приветствие: они работают
-- в продукте не первый месяц, и окно «Добро пожаловать» посреди рабочего
-- дня было бы не знакомством, а помехой. Датой стоит день заведения
-- участия, а не сегодняшний: это ближе к правде — знакомство у них
-- случилось тогда.
--
-- «Начало работы» им при этом не выключается: у работающей мойки все его
-- шаги уже выполнены по данным, и блок не показывается сам собой.

