-- Выплата за конкретный день, а не за отрезок.
--
-- Раньше выплата хранилась как «с … по …», и весь расчёт долга стоял на
-- одной черте: всё, что позже последней выплаты, — долг. В такой модели
-- нельзя выразить ни «день оплачен наполовину», ни «одна строка на день
-- в истории»: два нажатия в один день дают два отрезка и две записи.
--
-- Колонка пустая у старых строк, и это не недосмотр. Они закрывали
-- отрезок целиком, и разложить их обратно по дням честно нельзя — таких
-- данных не существует. Старые строки продолжают работать чертой,
-- новые всегда несут день.
ALTER TABLE "payouts" ADD COLUMN IF NOT EXISTS "day" date;
