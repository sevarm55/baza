-- Временный код доступа: форс-мажор, когда войти нечем.
--
-- Человек забыл код, а SMS не доходит — сменил номер, уехал, у нас
-- кончился баланс у оператора. Сброс доступа тут не помогает: он
-- оставляет вход только через SMS. Здесь админ платформы выдаёт
-- временный код, диктует его по телефону и записывает, что выдал.
--
-- Две колонки, а не отдельная таблица: код живёт ровно в том же поле
-- `pin_hash`, что обычный, и проверяется тем же сравнением. Отличие
-- только в сроке и в том, что после входа его просят сменить.
--
-- NULL в `temp_access_until` означает «код обычный». Так стоят все
-- существующие учётки, и ни одна не меняет поведения.

ALTER TABLE "accounts" ADD COLUMN IF NOT EXISTS "temp_access_until" timestamptz;
ALTER TABLE "accounts" ADD COLUMN IF NOT EXISTS "temp_access_by" text;
