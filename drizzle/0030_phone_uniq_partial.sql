-- Пустой телефон перестаёт быть занятым номером.
--
-- Регистрация переехала на почту, и телефон стал необязательным: код
-- заводит аккаунт с пустой строкой в `phone` и спрашивает номер потом, в
-- профиле. Уникальный индекс про это не знал — он стоял на всей колонке,
-- — и пустая строка вела себя как настоящий номер: первый же владелец,
-- зарегистрировавшийся почтой, занимал её собой, а второму приходил
-- отказ «этот номер уже зарегистрирован». Номера тот второй не вводил
-- вовсе.
--
-- Ломается это не сразу и потому особенно неприятно: первая регистрация
-- на чистой базе проходит, вторая нет, и выглядит это как поломка
-- регистрации целиком.
--
-- Лечится тем же приёмом, что уже применён к почте рядом: индекс
-- становится частичным. Уникальность настоящих номеров сохраняется
-- полностью, пустые перестают спорить друг с другом. NULL здесь не
-- годится: колонка `NOT NULL`, и снимать это ограничение ради одного
-- случая значит разрешить «номера нет» в двух написаниях сразу.

