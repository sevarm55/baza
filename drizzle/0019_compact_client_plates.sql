-- Один вид номера: слитно, без пробелов и дефисов.
--
-- Миграция 0017 привела номера к красивой форме `77 GG 477`. На практике
-- это оказалось хуже: на пластине номер написан слитно, мойщик набирает
-- его слитно, а продукт показывал иначе, чем человек ввёл. Возвращаем
-- слитную форму — ту, в которой номер и существует в жизни.
--
-- Столкновений быть не может: уникальный индекс из 0017 построен ровно
-- по этому выражению, поэтому двух строк с одинаковой слитной формой в
-- таблице уже нет.
UPDATE "clients"
SET "key" = regexp_replace(upper("key"), '[[:space:]-]+', '', 'g')
WHERE regexp_replace(upper("key"), '[[:space:]-]+', '', 'g')
  ~ '^[0-9]{2}[A-Z]{2}[0-9]{3}$'
  AND "key" <> regexp_replace(upper("key"), '[[:space:]-]+', '', 'g');
