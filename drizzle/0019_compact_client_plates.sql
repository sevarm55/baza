-- Наряды хранят номер снимком и обязаны совпадать с карточкой клиента:
-- по этой паре запись закрывает наряд.
UPDATE "jobs"
SET "client_key" = regexp_replace(upper("client_key"), '[[:space:]-]+', '', 'g')
WHERE "client_key" <> regexp_replace(upper("client_key"), '[[:space:]-]+', '', 'g');
