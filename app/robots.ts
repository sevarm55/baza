import type { MetadataRoute } from 'next';
import { isStaging } from '@/lib/staging';

/**
 * Что можно поисковикам.
 *
 * Файл появился ради тестового стенда, и боевое поведение он повторяет
 * ровно таким, каким оно было без него: до этого `robots.txt` не
 * отдавался вовсе, а отсутствие файла означает «разрешено всё». Менять
 * заодно и выдачу боевого сайта здесь нельзя — это отдельное решение с
 * отдельной ценой, и принимать его мимоходом, правя чужую задачу, не
 * стоит.
 *
 * Кабинет в запрете не нуждается: за ним стоит сессия, робот видит
 * только страницу входа. Админка закрыта отдельно и по-другому — тегом
 * в `app/admin/layout.tsx`, потому что её адрес незачем публиковать
 * даже строкой «сюда нельзя».
 *
 * Стенду индексация запрещена целиком. Причина не в секретности, а в
 * выдаче: стенд — это копия сайта на другом домене, и поисковик,
 * найдя две копии, показывает людям ту, которую выберет сам. Половина
 * посетителей попадала бы на пустую базу, где нет ни их мойки, ни их
 * абонемента.
 */
/**
 * Считается на запрос, а не на сборке.
 *
 * Без этой строки Next кэширует `robots.txt` как статику: он вычисляется
 * во время `next build`, когда переменной `STAGING` в окружении ещё нет
 * (она приезжает в контейнер на запуске), и стенд отдавал бы «индексируй
 * всё» при включённом запрете. Ошибка молчаливая — в логах чисто, а
 * стенд тем временем уходит в выдачу.
 *
 * Цена нулевая: ответ — четыре строки текста без единого обращения к
 * базе.
 */
export const dynamic = 'force-dynamic';

export default function robots(): MetadataRoute.Robots {
  if (isStaging()) {
    return { rules: { userAgent: '*', disallow: '/' } };
  }

  return { rules: { userAgent: '*', allow: '/' } };
}
