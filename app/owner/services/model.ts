/**
 * Форма данных прейскуранта.
 *
 * Через границу сервер-клиент уходят готовые значения: цена и в крупных
 * единицах (её правят в поле), и строкой с разрядами (её читают);
 * выручка месяца уже деньгами. Считать деньги в браузере незачем.
 */

/** Услуга в списке. */
export type ServiceRow = {
  id: string;
  name: string;
  /** цена в крупных единицах — её и правят в поле */
  price: number;
  /** та же цена, но уже разбитая на разряды: её читают */
  display: string;
  /** сколько раз брали за этот месяц */
  count: number;
  /** сколько принесла за месяц, уже деньгами */
  revenue: string;
  /** цена на каждый класс, в крупных единицах; 0 — «как базовая» */
  tierPrices: number[];
  /** те же цены строками с разрядами; пусто там, где своей цены нет */
  tierDisplay: string[];
};
