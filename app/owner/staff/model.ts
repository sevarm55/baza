/**
 * Форма данных страницы людей.
 *
 * Через границу сервер-клиент уходят готовые значения: деньги уже
 * посчитаны и отформатированы, состояние смены сведено к признаку, роль
 * названа словом ниши. Считать что-либо из этого второй раз в браузере
 * незачем — и опасно: заработок берётся из снимков процента в записях, а
 * не из текущей ставки человека.
 */

/** Человек в списке. */
export type StaffPerson = {
  id: string;
  name: string;
  phone: string;
  /** текущая ставка; в уже сделанных записях лежит её снимок */
  percent: number;
  /** «Սեփականատեր» или название роли этой ниши */
  roleLabel: string;
  /** владелец бизнеса: его нельзя отключить и у него другая роль */
  owner: boolean;
  /** себя отключить нельзя — владелец потеряет доступ к кабинету */
  canRemove: boolean;
  /** стоит на смене прямо сейчас */
  present: boolean;
  /** с какого часа стоит; пусто, когда не на смене */
  since: string | null;
  /** машин за этот месяц */
  count: number;
  /** начислено за месяц */
  earned: number;
  /** сколько ему сейчас должны — считает лист зарплат */
  due: number;
};
