/**
 * Форма данных сводки дня.
 *
 * Страница — серверный компонент, приборы внутри неё частью клиентские.
 * Через границу уходят готовые к показу значения, а не строки базы:
 * доля исполнителя, остаток бизнеса, цвет человека и подписанный способ
 * оплаты считаются один раз на сервере и приезжают числами.
 *
 * Причина не в экономии. Доля считается `staffShare` из снимка процента
 * в самой записи, и посчитать её второй раз в браузере значило бы завести
 * второй источник правды для денег — тот самый разлад, ради устранения
 * которого продукт написан.
 */

/** Участник работы: кто мыл и сколько ему за это начислено. */
export type OpWorker = {
  staffId: string | null;
  name: string | null;
  /** цвет человека: тот же, что в смене и на зарплатах */
  color: string;
  earned: number;
};

/** Запись о вымытой машине — строка сегодняшней работы. */
export type Op = {
  id: string;
  /** «14:00» в часовом поясе бизнеса */
  time: string;
  clientKey: string | null;
  /**
   * Кто мыл. Один человек — обычная запись, какой она была всегда;
   * несколько — совместная работа, и тогда машина всё равно ОДНА, а
   * разные у неё только получатели.
   *
   * Именно списком, а не одним именем плюс признаком: одно имя пришлось
   * бы выбирать — автора? первого? того, кто больше получил? — и любой
   * выбор врал бы про двух остальных.
   */
  crew: OpWorker[];
  /**
   * Кто ВНЁС запись.
   *
   * Отдельно от состава нарочно. Автор — факт оформления, участники —
   * факт работы, и совпадают они только у одиночной мойки. Владельцу
   * нужны оба ответа, но по разным поводам: состав он читает всегда,
   * автора — когда разбирается, откуда взялась запись.
   */
  authorName: string | null;
  serviceName: string;
  /** ключ способа оплаты: по нему фильтруют */
  payment: string;
  paymentLabel: string;
  /** сколько заплатил клиент */
  price: number;
  /**
   * Цена по прайсу, когда взяли меньше.
   *
   * Пусто, когда скидки не было, — и это единственное состояние, в
   * котором строка о ней молчит. До сих пор молчала всегда: скидку
   * продукт писал в базу и не показывал нигде, кроме уведомления в
   * момент записи.
   */
  listPrice: number | null;
  /**
   * Ставка в момент записи, а не текущая ставка человека.
   *
   * У совместной работы это процент КОМАНДЫ: весь зарплатный фонд
   * машины, который потом делится между участниками. Поэтому «45 %» под
   * записью, где каждому досталось по 1 800 с 12 000, — не ошибка, а
   * ровно то, о чём договаривались.
   */
  percent: number;
  /** начислено исполнителям — всем вместе */
  share: number;
  /** осталось бизнесу */
  yours: number;
};

/** Человек в сегодняшнем дне: на смене или уже отработавший. */
export type CrewMember = {
  staffId: string | null;
  name: string;
  color: string;
  /** стоит на смене прямо сейчас */
  present: boolean;
  /** «09:00» — когда он открыл смену; у отработавшего пусто */
  since: string | null;
  count: number;
  earned: number;
};


/** Доля одного способа оплаты в дневном приходе. */
export type MixSlice = {
  key: string;
  label: string;
  value: number;
  /** доля в процентах, целыми */
  share: number;
  color: string;
};

export type FlowPoint = {
  /** «11:00» для часа, «14» для дня месяца */
  label: string;
  /** приход за этот отрезок */
  value: number;
  /** сколько машин */
  count: number;
  /** кто их мыл: имена без повторов, не больше трёх */
  people: string[];
  /**
   * Отрезок, в котором мойка живёт прямо сейчас.
   *
   * Не «последний»: последним может оказаться час с записью, пришедшей
   * из будущего по кривым часам телефона, и подпись «сейчас» под ним
   * соврала бы. Час считается отдельно, по времени бизнеса.
   */
  now?: boolean;
};
