/**
 * Форма данных сводки дня.
 *
 * Страница — серверный компонент, приборы внутри неё частью клиентские.
 * Через границу уходят готовые к показу значения, а не строки базы:
 * доля исполнителя, остаток бизнеса, цвет человека и подписанный способ
 * оплаты считаются один раз на сервере и приезжают числами.
 *
 * Причина не в экономии. Доля считается `staffShare` из снимка процента
 * в самой записи, и посчитать её второй раз в браузере значило бы завести
 * второй источник правды для денег — тот самый разлад, ради устранения
 * которого продукт написан.
 */

/** Запись о вымытой машине — строка сегодняшней работы. */
export type Op = {
  id: string;
  /** «14:00» в часовом поясе бизнеса */
  time: string;
  clientKey: string | null;
  staffName: string | null;
  /** цвет человека: тот же, что в смене и на зарплатах */
  staffColor: string;
  serviceName: string;
  /** ключ способа оплаты: по нему фильтруют */
  payment: string;
  paymentLabel: string;
  /** сколько заплатил клиент */
  price: number;
  /** ставка в момент записи, а не текущая ставка человека */
  percent: number;
  /** начислено исполнителю */
  share: number;
  /** осталось бизнесу */
  yours: number;
};

/** Человек в сегодняшнем дне: на смене или уже отработавший. */
export type CrewMember = {
  staffId: string | null;
  name: string;
  color: string;
  /** стоит на смене прямо сейчас */
  present: boolean;
  count: number;
  earned: number;
};

/** Машина, которая сейчас во дворе: ждёт или моется. */
export type OpenCar = {
  id: string;
  clientKey: string;
  staffName: string | null;
  staffColor: string;
  serviceName: string | null;
  /** «Սպասում է» / «Ընդունված է» / «Լվացվում է» */
  state: string;
  /** «12 րոպե առաջ» */
  waited: string;
  washing: boolean;
};

/** Доля одного способа оплаты в дневном приходе. */
export type MixSlice = {
  key: string;
  label: string;
  value: number;
  /** доля в процентах, целыми */
  share: number;
  color: string;
};

/** Час дня или день периода на графике. */
export type FlowPoint = {
  /** «11:00» для часа, «14» для дня месяца */
  label: string;
  /** приход за этот отрезок */
  value: number;
  /** сколько машин */
  count: number;
  /** кто их мыл: имена без повторов, не больше трёх */
  people: string[];
  /**
   * Отрезок, в котором мойка живёт прямо сейчас.
   *
   * Не «последний»: последним может оказаться час с записью, пришедшей
   * из будущего по кривым часам телефона, и подпись «сейчас» под ним
   * соврала бы. Час считается отдельно, по времени бизнеса.
   */
  now?: boolean;
};
