import Link from 'next/link';
import { Plus, ReceiptText } from 'lucide-react';
import { getDict } from '@/lib/i18n/server';

/**
 * Два действия, за которыми владелец берёт телефон.
 *
 * На компьютере их искать не нужно: разделы стоят слева и видны всегда,
 * а «записать машину» и «записать расход» это один клик по меню. На
 * телефоне разделов на экране нет вовсе, и то же самое стоило бы двух
 * нажатий — вкладка, потом кнопка в заголовке раздела.
 *
 * Действий ровно два, и третье не выдумано. Лаймовая кнопка в продукте
 * значит «единственное, что здесь жмут»; две таких рядом означали бы,
 * что главного нет, поэтому громкая одна — запись машины, за ней сюда
 * заходят по сорок раз в смену. Расход стоит рядом и тише: его заводят
 * раз в день, но заводят с телефона, стоя у кассы с чеком в руке.
 *
 * Ряда нет на широком экране: там он повторял бы то, что и так написано
 * в боковой колонке, и отбирал бы высоту у графика.
 */
export async function QuickActions({
  /** «մեքենա» в винительном: кнопка обещает записать именно её */
  unitAcc,
}: {
  unitAcc: string;
}) {
  const t = await getDict();

  return (
    <nav className="qa mt-[var(--seam)] md:hidden" aria-label={t.phone.quick}>
      {/* Ведёт на экран смены: запись живёт там, вместе со сменой и
          журналом. Отдельной формы записи в кабинете нет намеренно —
          машину записывают в одном месте, и второе такое место
          означало бы две ленты, которые надо сверять. */}
      <Link href="/work" className="qa-item" data-primary>
        <Plus className="size-4 shrink-0" aria-hidden />
        <span>{unitAcc}</span>
      </Link>

      {/* Открывает форму сразу, а не страницу с кнопкой: расход
          записывают с чеком в руке, и лишний экран между намерением и
          полем суммы — это тот самый шаг, на котором расход не
          записывают вовсе. */}
      <Link href="/owner/expenses?new=1" className="qa-item">
        <ReceiptText className="size-4 shrink-0" aria-hidden />
        <span>{t.phone.addExpense}</span>
      </Link>
    </nav>
  );
}
