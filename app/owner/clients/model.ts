/**
 * Форма данных клиентской базы.
 *
 * Клиент в TETRIN — это машина, а не человек: при записи мойщик вводит
 * номер, и по нему же машина узнаётся в следующий раз. Имя и телефон
 * появляются позже, из карточки, и есть далеко не у всех.
 *
 * Придумывать поверх этого «человека с несколькими автомобилями» было бы
 * враньём в модели: продукт такой связи не хранит и связать две машины
 * одного владельца не может. Интерфейс честно показывает то, что есть, —
 * и ищет по всему, что владелец мог вписать.
 */

/** Строка списка. */
export type ClientRow = {
  id: string;
  /** номер машины: он же ключ и он же то, что ищут */
  key: string;
  name: string | null;
  phone: string | null;
  visits: number;
  total: number;
  /** сколько суток молчит */
  days: number;
  /** «сегодня» / «3 օր առաջ» — считает сервер */
  last: string;
  /** средний чек этой машины */
  avg: number;
};

/**
 * Группа, по которой отбирают.
 *
 * Пороги не выдуманы: «свой человек» — это больше одного визита, а
 * «пропал» — та же граница, по которой загорается колокольчик
 * (`LOST_AFTER_DAYS`). Два разных правила на одно состояние означали бы,
 * что продукт спорит сам с собой: в колокольчике повод есть, в списке
 * тихо.
 */
export type ClientGroup = 'all' | 'fresh' | 'loyal' | 'lost';

/** Порядок списка. */
export type ClientSort = 'recent' | 'often' | 'richest';
