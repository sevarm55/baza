/**
 * Что страница зарплат показывает — и чем это отличается от того, что
 * лежит в базе.
 *
 * В базе три разные вещи: заработанное по дням, отданное по дням и
 * записи о выдачах. На экране они обязаны сложиться в один ответ на
 * вопрос «кому я должен и за какой день», поэтому вся склейка происходит
 * на сервере, один раз, а в браузер уезжают уже готовые группы.
 *
 * Главное правило этих типов: рабочий день и день выплаты никогда не
 * лежат в одном поле. `DayGroup.day` — это когда работали, `HistoryDay`
 * — когда отдавали деньги, и перепутать их нельзя даже случайно.
 */

/* Разложение суммы по машинам приходит с сервера как есть, поэтому и тип
   у него общий. `import type` тут обязателен: он стирается при сборке, и
   через него в клиентский бандл не утаскивается драйвер базы. */
import type { BoardLine } from '@/lib/payroll-board';

/** Машина, из которой сложилась дневная доля человека. */
export type OrderLine = BoardLine;

/** Человек внутри рабочего дня. */
export type StaffEntry = {
  /** `${day}|${staffId}` — по нему идёт выбор и по нему же платят */
  key: string;
  /** пусто у записей без исполнителя: платить по ним некому */
  staffId: string | null;
  name: string;
  color: string;
  count: number;
  /** сколько за этот день ещё должны */
  earned: number;
  /** ставка, по которой посчитано: «20%» или вилка «20–40%» */
  rate: string | null;
  /** сколько за этот день уже отдано */
  paid: number;
  /** когда отдали, коротко для строки: «14 օգս, 16:25» */
  paidAt: string | null;
  /** то же полной фразой — для подсказки и озвучки: «Վճարվել է 14 օգոստոսի, 16:25» */
  paidNote: string | null;
  /** разложение по машинам; пусто, если полного разложения нет */
  lines: OrderLine[] | null;
};

/** Рабочий день целиком: и долг, и уже закрытое. */
export type DayGroup = {
  /** `YYYY-MM-DD` в часовом поясе бизнеса */
  day: string;
  /** «Այսօր · 14 օգոստոսի» или «13 օգոստոսի» */
  title: string;
  today: boolean;
  people: StaffEntry[];
  /** машин за день — по тем людям, что показаны */
  units: number;
  /** сколько по этому дню ещё должны */
  outstanding: number;
  /** сколько по этому дню уже отдано */
  paid: number;
};

/** Одна выдача: сколько человек за раз получили деньги из рук в руки. */
export type HistoryPayment = {
  key: string;
  /** «16:25» — когда отдали */
  time: string;
  /** «13 օգոստոսի աշխատանքի համար» — за какой рабочий день */
  forWork: string;
  /** машин за тот рабочий день, если это ещё известно */
  units: number | null;
  rows: { id: string; name: string; color: string; amount: number }[];
  total: number;
};

/** День выплаты — не рабочий день. */
export type HistoryDay = {
  key: string;
  /** «Այսօր · 14 օգոստոսի» */
  title: string;
  payments: HistoryPayment[];
};

/** Что выбрано к выплате: человек и рабочий день, за который платят. */
export type PayItem = { staffId: string; day: string };
