/**
 * Форма данных страницы расходов.
 *
 * Через границу сервер-клиент уходят готовые к показу значения, а не
 * строки базы: доля периода считается в SQL тем же выражением, что итог
 * наверху (`shareOfPeriod`), дата собирается в часовом поясе бизнеса, а
 * сумма приезжает сразу в двух видах — числом для поля правки и
 * разрядами для чтения.
 *
 * Причина та же, что у сводки дня: посчитать долю второй раз в браузере
 * значило бы завести второй источник правды для денег.
 */

/** Одна строка расхода. */
export type ExpenseItem = {
  id: string;
  category: string;
  /** постоянный (аренда) или разовый (канистра химии) */
  monthly: boolean;
  /** номинал: сколько расход стоит целиком */
  amount: number;
  /** сколько из него пришлось на выбранный месяц */
  share: number;
  /** дневная доля постоянного; у разового ноль */
  perDay: number;
  /** сумма в крупных единицах — её правят в поле */
  major: number;
  /** та же сумма разрядами, без знака валюты: её читают */
  display: string;
  /** «15 օգոստոսի» — когда потрачено или с какого дня действует */
  day: string;
  /** «2026-08-15» — им же заполняется поле даты в правке */
  dayKey: string;
  /**
   * Постоянный расход закрыт задним числом.
   *
   * Такая строка — история: аренда, которую подняли, остаётся в прошлом
   * месяце по старой цене. Править её нельзя, иначе прибыль за уже
   * прожитые дни перепишется задним числом.
   */
  closed: boolean;
  /** «մինչև 12 օգոստոսի» у закрытого; пусто у действующего */
  closedOn: string | null;
  note: string | null;
};

/** Разовые расходы одного дня. */
export type ExpenseDay = {
  key: string;
  /** «Այսօր · 15 օգոստոսի» */
  title: string;
  total: number;
  items: ExpenseItem[];
};
