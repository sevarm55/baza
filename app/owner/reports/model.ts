/**
 * Форма данных отчёта.
 *
 * Через границу сервер-клиент уходит только то, что рисует график:
 * подпись месяца, три величины и адрес, по которому этот месяц
 * открывается. Даты, имена месяцев и деньги считаются на сервере — в
 * поясе бизнеса и одним форматером на весь продукт.
 */

/** Месяц на графике. */
export type TrendPoint = {
  /** ISO первого числа — устойчивый ключ строки */
  key: string;
  /** «օգոստ.» — короткое имя месяца под столбиком */
  label: string;
  /** куда ведёт нажатие по столбику */
  href: string;
  /** этот месяц сейчас открыт */
  current: boolean;
  revenue: number;
  profit: number;
  count: number;
};

/** Величина, по которой построен график. */
export type Metric = 'profit' | 'revenue' | 'count';
