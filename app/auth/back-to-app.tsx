'use client';

import { useEffect } from 'react';

import { AuthButton, AuthHead } from '@/components/landing/auth-ui';
import { useT } from '@/lib/i18n/client';

/**
 * Возвращение в приложение после ссылки из письма.
 *
 * Ссылку открывает браузер, и по-другому не бывает: письмо читают почтой,
 * почта отдаёт ссылку системе, система — браузеру. Но человек, начавший в
 * приложении, не просил ни браузера, ни кабинета: он ушёл на минуту
 * подтвердить адрес и ждёт, что вернётся туда, откуда ушёл.
 *
 * Поэтому здесь СРАЗУ пробуем открыть приложение своей схемой и рядом
 * оставляем кнопку. Кнопка не запасной путь для красоты: автоматический
 * переход браузер имеет право не выполнить, а из встроенного браузера
 * Gmail он и вовсе срабатывает через раз. Нажатие человека — единственное
 * событие, которому браузер верит всегда.
 *
 * Этот экран показывается ТОЛЬКО тем, кто пришёл из приложения (признак
 * едет в самой заявке). Пришедшего с сайта незачем выкидывать в
 * приложение, которого у него может не быть: попытка открыть неизвестную
 * схему показала бы ему окно с ошибкой вместо кабинета.
 */
export function BackToApp({ email }: { email: string }) {
  const t = useT();
  const link = `tetrin://signin?login=${encodeURIComponent(email)}`;

  useEffect(() => {
    /* Небольшая задержка намеренно: без неё переход случается в том же
       кадре, что и отрисовка, и человек не успевает увидеть, что всё
       получилось. Вернувшись из приложения, он оказался бы на странице,
       которую не читал. */
    const t = setTimeout(() => {
      window.location.href = link;
    }, 400);
    return () => clearTimeout(t);
  }, [link]);

  return (
    <div className="flex flex-col gap-8">
      <AuthHead title={t.auth.readyTitle} subtitle={t.auth.backToAppNote} />
      <AuthButton type="button" onClick={() => (window.location.href = link)}>
        {t.auth.openApp}
      </AuthButton>
    </div>
  );
}
