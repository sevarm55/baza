/**
 * Числа витрины — одна смена вымышленной мойки.
 *
 * Это ДАННЫЕ ДЛЯ ПОКАЗА, а не расчёт. Логика продукта живёт в
 * `lib/expenses.ts`, `lib/money.ts` и запросах; здесь лежит смена,
 * которую эта логика могла бы посчитать, — чтобы витрина показывала
 * настоящий кабинет с настоящей арифметикой, а не подобранные красивые
 * цифры.
 *
 * ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: всё сходится. Витрина продаёт учёт денег,
 * и человек, который сложит столбец глазами и получит другое число,
 * закроет страницу. Складывать можно что угодно на любом экране.
 *
 * Смена показана в двух состояниях, и это её главный приём.
 *
 * ДО (то, что лежит здесь):
 *   машины     13 + 12 + 11                        = 36
 *   выручка    88 000 + 80 000 + 72 000            = 240 000
 *   зарплата   22 000 + 20 000 + 18 000  (по 25 %) = 60 000
 *   расходы    10 000 + 6 500                      = 16 500
 *   остаётся   240 000 − 60 000 − 16 500           = 163 500
 *
 * ПОСЛЕ того как на глазах записали машину (35 AA 777, 8 000 ֏, Арман):
 *   машины 37, выручка 248 000, зарплата 62 000    → остаётся 169 500
 *
 * ПОСЛЕ того как на глазах вписали воду (18 000 ֏):
 *   расходы 34 500                                 → остаётся 151 500
 *
 * Ровно эти два перехода витрина и показывает: число меняется между
 * двумя настоящими состояниями смены, а не крутится от нуля. Показание —
 * это факт, а не барабан (DESIGN.md §11).
 *
 * Имена людей, услуги и категории лежат в словаре: их читают на своём
 * языке. Здесь только то, что от языка не зависит, — числа, время и
 * номера машин (на армянских номерах латиница).
 */

/** Отрезок графика: сколько денег и сколько машин за час или за день. */
export type DemoPoint = { label: string; revenue: number; count: number };

/** Показатели периода — те же пять, что считает кабинет. */
export type DemoTotals = {
  count: number;
  revenue: number;
  payroll: number;
  costs: number;
  net: number;
};

/** Машина в списке. Услуга, оплата и человек — индексами в словарь. */
export type DemoOrder = {
  time: string;
  plate: string;
  service: number;
  payment: number;
  staff: number;
  price: number;
};

/** Событие ленты смены. */
export type DemoEvent = {
  time: string;
  staff: number;
  kind: 'added' | 'opened';
  plate: string | null;
};

