'use client';

import { AuthTrigger } from '@/components/auth-buttons';
import { useT } from '@/lib/i18n/client';
import { TRIAL_DAYS } from '@/lib/plan';
import s from './landing.module.css';

/**
 * Что это за продукт — сказано ПОСЛЕ того, как его показали.
 *
 * Наверху страницы больше нет вступления. Оно там стояло плакатом:
 * надзаголовок капсом, заголовок в полсотни пунктов, строка под ним,
 * кнопка, ссылка, срок пробного и подпись про то, что лежит ниже. Семь
 * этажей обещаний перед первым настоящим экраном, и все они говорили
 * то же, что первый экран показывает сам за две секунды.
 *
 * Хуже размера был голос. Вся страница ниже набрана тихо и точно —
 * числа, волосяные линии, мелкие подписи; плакат сверху кричал, и
 * читалось это как чужая шапка, приклеенная к чужому продукту.
 *
 * Теперь порядок обратный: сначала на глазах записывается машина, и
 * только потом страница называет себя, объясняет, из чего состоит, и
 * просит зарегистрироваться. Заголовок остался тем же и остался
 * заголовком страницы (`h1`) — он сменил не слова, а место и рост.
 */
export function Pitch() {
  const l = useT().landing;

  return (
    <div className={s.pitch}>
      {/* Заголовок страницы набран обычной строкой, а не плакатом.

          Второй крупной надписи подряд здесь быть не должно: прямо над
          этим местом стоит заголовок первой сцены, и два заголовка
          в один рост читаются заиканием. Роль `h1` при этом остаётся
          настоящей — это единственное предложение, которое называет
          продукт целиком. */}
      <h1 className={s.pitchLead}>{l.hero.lead}</h1>

      <div className={s.pitchActions}>
        <AuthTrigger mode="register" className={s.cta}>
          {l.hero.cta} <span aria-hidden="true">↗</span>
        </AuthTrigger>
        <span className={s.note}>{l.hero.note(TRIAL_DAYS)}</span>
      </div>
    </div>
  );
}
