import { NextResponse } from 'next/server';
import { endSession } from '@/lib/auth';

/**
 * Выход для протухшей сессии.
 *
 * Cookie нельзя удалить во время отрисовки страницы — только в действии
 * или в обработчике маршрута. Поэтому экраны, обнаружившие, что сессия
 * указывает на несуществующий бизнес, ведут сюда, а не сразу на вход.
 *
 * Без этого получалась петля: `/owner` не находил бизнес и отправлял на
 * `/login`, `/login` видел живую cookie и отправлял обратно на `/owner`.
 * Браузер крутился между ними, пока не сдавался. Случай редкий (бизнес
 * удалён, база пересоздана), но выбраться из него человек сам не мог.
 */
export async function GET() {
  await endSession();

  /* Адрес относительный, и это принципиально. `new URL(..., request.url)`
     собирал абсолютный: за прокси `request.url` — это внутренний адрес
     контейнера, `http://0.0.0.0:3000`, и человека уносило туда, где
     браузеру некуда стучаться. На бою это выглядело так: сменил пароль,
     сессия закрылась, и вместо окна входа «Не удаётся получить доступ к
     сайту».

     Относительный `Location` разрешён HTTP и разбирается браузером
     относительно того адреса, по которому он пришёл. Значит он верен и
     на `tetrin.pro`, и на стенде, и на localhost, и ничего про себя
     знать не нужно. */
  return new NextResponse(null, {
    status: 303,
    headers: { Location: '/?auth=signIn' },
  });
}
