import SwiftUI

/**
 * Язык движения Tetrin.
 *
 * Те же числа, что в `lib/motion.ts` на вебе и в
 * `android/.../design/Motion.kt`. Продукт один, и человек, который утром
 * смотрит выручку в браузере, а днём записывает машину с телефона, не
 * должен замечать, что переходы там и тут разной длины: расхождение он
 * не назовёт словами, но почувствует как «в приложении что-то тормозит».
 *
 * Каждая длительность имеет свою работу, и брать соседнюю «на глаз»
 * нельзя: `instant` для того, что обязано успеть под пальцем, `fast` для
 * смены состояния детали, `normal` для прихода содержимого, `slow` для
 * перестроения фигуры.
 */
enum Motion {
    /// Нажатие, отклик под пальцем.
    static let instant: Double = 0.11
    /// Смена состояния мелкой детали.
    static let fast: Double = 0.17
    /// Появление содержимого, перекрёстное затухание.
    static let normal: Double = 0.24
    /// Перестроение фигуры, морф.
    static let slow: Double = 0.45
    /// Полный оборот фирменного загрузчика.
    static let loaderCycle: Double = 1.35

    /// Пружина для крупного: лист, окно, перестроение.
    static let springSoft = Animation.spring(response: 0.42, dampingFraction: 0.82)
    /// Пружина для мелкого: галочка, отметка выбора, нажатие.
    static let springSnap = Animation.spring(response: 0.28, dampingFraction: 0.72)

    /// Приход содержимого на место скелета.
    static let content = Animation.easeOut(duration: normal)

    /**
     * Сколько ждать, прежде чем показать, что идёт загрузка.
     *
     * Запрос на девяносто миллисекунд, отмеченный скелетом, выглядит
     * хуже, чем тот же запрос без ничего: человек видит вспышку серых
     * прямоугольников и считает, что экран дрогнул.
     *
     * Готовый ответ при этом никогда не придерживаем: порог откладывает
     * показ загрузки, а не показ данных.
     */
    static let loadingDelay: Duration = .milliseconds(180)

    /// Сколько держится отметка «получилось».
    static let successHold: Duration = .milliseconds(1400)
}

/**
 * Кривые для ручной интерполяции.
 *
 * Нужны там, где анимацию считает не SwiftUI, а мы сами по времени, —
 * то есть в фирменном загрузчике. Он живёт на `TimelineView`, а не на
 * `repeatForever`, и подставлять `Animation` туда некуда.
 */
enum Ease {
    /// Мягкий разгон и мягкое торможение.
    static func inOut(_ x: Double) -> Double { x * x * (3 - 2 * x) }

    /// Резкий выход, мягкое гашение.
    static func out(_ x: Double) -> Double { 1 - pow(1 - x, 3) }

    /// Длинный выкат: то же, что `cubic-bezier(0.16, 1, 0.3, 1)` на вебе.
    static func soft(_ x: Double) -> Double { 1 - pow(1 - x, 5) }

    /// Пружина с еле заметным перелётом.
    static func spring(_ x: Double) -> Double {
        let c1 = 0.7, c3 = c1 + 1
        let t = x - 1
        return 1 + c3 * t * t * t + c1 * t * t
    }

    static func linear(_ x: Double) -> Double { x }
}
