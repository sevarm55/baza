import SwiftUI

/**
 * Такт, в котором сейчас стоит содержимое сцены.
 *
 * Онбординг у нас не листалка, а смена кадров: старый кадр уходит целиком,
 * сцена долю секунды стоит пустой, новый собирается по элементам. Эти три
 * состояния и есть такты, и они общие для всего, что на сцене нарисовано,
 * — потому и заведены одним значением, а не флагом у каждого элемента.
 */
enum Beat {
    /// Ещё не пришло: спрятано, размыто и ждёт своей задержки.
    case waiting
    /// На месте.
    case here
    /// Уходит: уезжает вбок и гаснет, всё разом.
    case leaving
}

/**
 * В какую сторону уходит кадр.
 *
 * По умолчанию влево: человек идёт вперёд. Назад по свайпу кадр обязан
 * уехать вправо, иначе движение спорит с жестом — палец ведёт вправо, а
 * картинка уезжает влево, и рука не верит экрану.
 *
 * Сторона лежит в окружении, а не в параметре модификатора: задаёт её
 * экран целиком и один раз, а помечено ею полтора десятка элементов. В
 * параметре это полтора десятка мест, где её можно забыть проставить.
 */
private struct RevealBackKey: EnvironmentKey {
    static let defaultValue = false
}

extension EnvironmentValues {
    var revealBack: Bool {
        get { self[RevealBackKey.self] }
        set { self[RevealBackKey.self] = newValue }
    }
}

extension View {
    /**
     * Место элемента в очереди прихода. Ноль приходит первым.
     *
     * Соседние номера разделены `Motion.revealStep`. Очередь читается
     * прямо в разметке экрана сверху вниз, а не собирается в голове из
     * задержек, разбросанных по файлу.
     */
    func reveal(_ beat: Beat, step: Int = 0) -> some View {
        modifier(Reveal(beat: beat, step: step))
    }
}

/**
 * Приход содержимого размытием.
 *
 * ВЕДУЩИЙ ПАРАМЕТР ЗДЕСЬ БЛЮР, А НЕ ПРОЗРАЧНОСТЬ. Разница не в красоте:
 * элемент, который просто проявляется из ничего, читается как «включили»,
 * а тот же элемент, который вплывает из размытия, читается как «поднесли
 * ближе». Второе — это материал, у него есть положение в глубине, и
 * поэтому карточка с показанием выглядит вещью, а не картинкой.
 *
 * Прозрачность и сдвиг тоже есть, но они добирают: сами по себе они дают
 * обычное всплывание снизу, каких на любом экране по десятку.
 *
 * Уход устроен иначе прихода намеренно. Приходят по очереди, чтобы кадр
 * собирался и читался; уходят разом и вбок, потому что уход не сообщение,
 * а освобождение сцены, и растягивать его незачем.
 *
 * При системном «уменьшить движение» остаётся одна прозрачность: размытие
 * и сдвиг — ровно то, от чего у части людей кружится голова.
 */
private struct Reveal: ViewModifier {
    let beat: Beat
    let step: Int

    @Environment(\.accessibilityReduceMotion) private var calm
    @Environment(\.revealBack) private var back

    func body(content: Content) -> some View {
        content
            .blur(radius: blur)
            .opacity(beat == .here ? 1 : 0)
            .scaleEffect(scale)
            .offset(x: slide, y: lift)
            .animation(curve, value: beat)
    }

    /// Насколько элемент размыт. На месте — ноль, и тогда SwiftUI слой
    /// размытия не считает вовсе.
    private var blur: CGFloat {
        guard !calm else { return 0 }
        switch beat {
        case .waiting: return 16
        case .here: return 0
        case .leaving: return 8
        }
    }

    /// Приходит чуть уменьшенным: вместе с размытием это и есть «дальше по
    /// глубине». Проценты малые — крупный масштаб превратил бы приход в
    /// прыжок, а прыгает в продукте только то, на что нажали.
    private var scale: CGFloat {
        !calm && beat == .waiting ? 0.97 : 1
    }

    /// Уход вбок. Вперёд — влево, назад — вправо.
    private var slide: CGFloat {
        guard !calm, beat == .leaving else { return 0 }
        return back ? 44 : -44
    }

    /// Приход снизу вверх, коротко.
    private var lift: CGFloat {
        !calm && beat == .waiting ? 12 : 0
    }

    /**
     * Кривая.
     *
     * У прихода длинный выкат `(0.16, 1, 0.3, 1)` — тот же, которым
     * собирается заставка запуска, и та же причина: движение обязано
     * закончиться раньше, чем человек успеет заметить его конец.
     *
     * У ухода разгон, а не выкат: кадр уходит с ускорением и без задержки
     * на очередь. Задержка на уходе — самая частая ошибка в таких
     * переходах: человек нажал, а экран ещё полсекунды разбирается.
     */
    private var curve: Animation {
        if beat == .leaving {
            return .easeIn(duration: Motion.fast)
        }
        return .timingCurve(0.16, 1, 0.3, 1, duration: Motion.reveal)
            .delay(Double(step) * Motion.revealStep)
    }
}
