import SwiftUI

/**
 * Марка Tetrin, набранная.
 *
 * Последние две буквы стоят в плашке: «TETR» цветом и «IN» вывороткой на
 * нём же. Приём нужен затем же, зачем он нужен любому логотипу из одного
 * слова, — чтобы слово перестало быть подписью и стало знаком. Читается
 * оно при этом ровно так же, а на маленьком размере плашка остаётся
 * заметной, когда сами буквы уже нет.
 *
 * Знак повторяет тот, что в браузере (`components/wordmark.tsx`), вплоть
 * до шрифта: Unbounded Black, тот же файл, что и на витрине. До сих пор
 * приложение набирало марку системным шрифтом, и на двух экранах одного
 * продукта стояли два разных знака — а разные знаки читаются подделкой
 * быстрее, чем замечается разница в буквах.
 *
 * Раскол по последним двум буквам, а не по вписанному «IN»: имя лежит в
 * одном месте и не должно оказаться записанным дважды. Сменят имя — знак
 * соберётся из нового.
 */
struct Wordmark: View {
    /// Кегль. Обычно 15: марка это подпись над заголовком, а не заголовок.
    var size: CGFloat = 15
    /// Цвет букв. Плашка красится им же, а буквы в ней — цветом полотна.
    var tint: Color = Brand.lime
    /**
     * Цвет букв ВНУТРИ плашки.
     *
     * Тёмный грейп, а не светлый: `Brand.grape` на тёмной теме
     * подсвечивается до сиреневого, и «IN» на лайме горел вторым ярким
     * пятном вместо выворотки. Здесь нужен ровно тот цвет, которым в
     * продукте пишут ПО лайму, — он для этого и заведён.
     */
    var on: Color = Brand.onLime

    private let name = "TETRIN"

    var body: some View {
        HStack(spacing: 0) {
            Text(name.prefix(name.count - 2))
                /* Разрядка меньше, чем у системного шрифта: Unbounded сам
                   по себе широкий, и прежние крупные просветы растаскивали
                   имя на пол-экрана. */
                .tracking(size * 0.1)

            Text(name.suffix(2))
                .tracking(size * 0.1)
                .foregroundStyle(on)
                /* Поле по бокам в долях кегля, а не в точках: знак стоит и
                   в 15, и в 22, и в точках на мелком он превратился бы в
                   толстую подушку вокруг двух букв. Справа разрядка
                   съедает столбик, поэтому поле там меньше. */
                .padding(.leading, size * 0.22)
                .padding(.trailing, size * 0.12)
                .padding(.vertical, size * 0.16)
                .background(tint, in: .rect(cornerRadius: size * 0.22))
                .padding(.leading, size * 0.14)
        }
        .font(.custom("Unbounded-Black", size: size))
        .foregroundStyle(tint)
        .accessibilityHidden(true)
    }
}
