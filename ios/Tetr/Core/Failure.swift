import Foundation

/**
 * Что сказать человеку, когда экран не загрузился.
 *
 * ЗАЧЕМ ОТДЕЛЬНО. В пяти экранах стояло `failure = "\(error)"` — и пока
 * ошибки были сетевыми, это почти работало. Стоило ответу сервера
 * разойтись с моделью на одно поле, и владелец мойки увидел на весь
 * экран `keyNotFound(CodingKeys(stringValue: "revenue"...` — текст,
 * который ничего ему не сообщает и выглядит как сломанный продукт.
 *
 * Здесь три случая и три разных ответа, потому что делать с ними человек
 * должен разное:
 *
 *   связи нет     — подождать и потянуть вниз; это не поломка;
 *   сервер отказал— показать код: с ним можно позвонить и назвать его;
 *   всё остальное — «не удалось». Разбор ответа, нехватка памяти,
 *                   неизвестный формат даты — это наши беды, а не его, и
 *                   переложить их на него текстом ошибки значит
 *                   попросить о помощи того, кто пришёл за выручкой.
 *
 * Техническая подробность при этом не теряется: она уходит в консоль,
 * где её читает тот, кто может починить.
 */
enum Failure {
    static func text(_ error: Error, where place: String = #function) -> String {
        if let api = error as? APIError {
            return api.isOffline
                ? L("errors.offline")
                : L("errors.server", "\(api.status) \(api.code ?? "—")")
        }

        /* Отмена — не ошибка: так выглядит отпущенное «потянуть вниз» и
           уход с экрана. Сообщать о ней нечего. */
        if error is CancellationError { return "" }

        print("[\(place)] \(error)")
        return L("payroll.failed")
    }
}
