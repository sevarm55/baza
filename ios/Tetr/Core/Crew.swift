import Foundation

/**
 * Совместная работа: одна машина, несколько исполнителей.
 *
 * Здесь только арифметика — ни сети, ни экранов. Причина та же, по
 * которой цена по классу считается в одном месте: сервер делит фонд при
 * записи, экран показывает будущую долю до нажатия кнопки, кабинет
 * объясняет уже посчитанное. Три ответа на один вопрос, и разойтись им
 * негде только пока формула одна.
 *
 * Слово в слово повторяет `lib/crew.ts` на сервере. Расхождение здесь
 * означало бы, что мойщик видит на экране одно число, а вечером в
 * ведомости другое, — то есть ровно тот спор, ради устранения которого
 * продукт написан.
 *
 * ПРАВИЛО ЦЕЛИКОМ:
 *
 *   моет один   → фонд = цена × ЛИЧНЫЙ процент этого человека;
 *   моют двое+  → фонд = цена × ОБЩИЙ процент команды, делится поровну.
 *
 * Общий процент — это не «по столько каждому». Пятьдесят процентов на
 * троих означают пять тысяч с десятитысячной машины на всех, а не
 * пятнадцать.
 */
enum Crew {
    /// Сколько человек максимум может мыть одну машину. То же, что `MAX_CREW`.
    static let maxSize = 8

    /**
     * Зарплатный фонд машины.
     *
     * Округление вниз — то же самое, которым продукт считает долю
     * одиночного мойщика с самого начала. Второй способ округлять означал
     * бы, что совместная работа на одного человека даёт не ту сумму, что
     * одиночная, при одинаковом проценте.
     */
    static func pool(price: Int, percent: Int) -> Int {
        price * percent / 100
    }

    /**
     * Разделить фонд между участниками.
     *
     * ОСТАТОК НЕ ТЕРЯЕТСЯ И НЕ ПРИДУМЫВАЕТСЯ. Пять тысяч на троих — это не
     * «по 1 666,67»: дробных драмов не бывает, а сумма долей обязана до
     * последней единицы совпасть с фондом. Иначе ведомость не сходится с
     * расходом на зарплату, и расхождение всплывает у владельца ровно
     * там, где продукт обещал порядок.
     *
     * Поэтому 5 000 на троих дают 1 667 + 1 667 + 1 666. Лишние единицы
     * уходят первым по порядку, а первый — тот, кто вносит запись.
     */
    static func split(pool: Int, people: Int) -> [Int] {
        guard people > 0 else { return [] }
        let base = pool / people
        let extra = pool - base * people
        return (0..<people).map { base + ($0 < extra ? 1 : 0) }
    }

    /// Сколько получит каждый при такой цене, ставке и числе участников.
    static func shares(price: Int, percent: Int, people: Int) -> [Int] {
        split(pool: pool(price: price, percent: percent), people: people)
    }
}
