import Foundation

/**
 * Проверка слов, которые склоняются.
 *
 * Не XCTest — по той же причине, что и у разбора номера: прогоняется
 * одной командой вместе с остальным, без тестового таргета.
 *
 *   xcrun simctl launch <udid> com.sevarm.tetr --self-test
 *
 * Проверяется ровно то, что уже ломалось на живом экране:
 *
 *  — русский интерфейс с армянским словом на главной кнопке. Термины
 *    приходят с сервера, а язык переключают внутри приложения — и без
 *    перевода на месте кнопка записи оставалась «+ մեքենա» под русским
 *    заголовком;
 *  — «0 машина» вместо «0 машин». Форма слова после числительного у
 *    каждого языка своя, и склейка `"\(n) \(unitOne)"` врёт по-русски
 *    на большинстве чисел;
 *  — слово, переписанное владельцем. Его перевода нет и быть не может,
 *    и продукт обязан оставить его в покое на любом языке.
 */
enum TermsTests {
    static func run() -> Int {
        var failed = 0

        func check(_ name: String, _ got: String, _ want: String) {
            if got == want {
                print("  ok   \(name)")
            } else {
                failed += 1
                print("  FAIL \(name): получили «\(got)», ждали «\(want)»")
            }
        }

        let saved = LangStore.currentLang
        defer { LangStore.testOnlySet(saved) }

        // ── армянский: исходный язык, всё остаётся как было ──
        LangStore.testOnlySet(.hy)
        check("hy: единица", Terms.unit("մեքենա").nom, "մեքենա")
        check("hy: на кнопке", Terms.unit("մեքենա").acc, "մեքենա")
        // после числительного армянский ставит единственное всегда
        check("hy: 0", Terms.units(0, "մեքենա"), "0 մեքենա")
        check("hy: 5", Terms.units(5, "մեքենա"), "5 մեքենա")
        check("hy: исполнитель", Terms.staff("Լվացող").nom, "Լվացող")

        // ── русский: три формы, и ни одной склейки ──
        LangStore.testOnlySet(.ru)
        check("ru: слово ниши переведено", Terms.unit("մեքենա").nom, "машина")
        check("ru: на кнопке — винительный", Terms.unit("մեքենա").acc, "машину")
        check("ru: подпись плитки — множественное", Terms.unit("մեքենա").many, "машины")
        check("ru: 0", Terms.units(0, "մեքենա"), "0 машин")
        check("ru: 1", Terms.units(1, "մեքենա"), "1 машина")
        check("ru: 3", Terms.units(3, "մեքենա"), "3 машины")
        check("ru: 5", Terms.units(5, "մեքենա"), "5 машин")
        check("ru: 11 — не «11 машина»", Terms.units(11, "մեքենա"), "11 машин")
        check("ru: 21", Terms.units(21, "մեքենա"), "21 машина")
        check("ru: 22", Terms.units(22, "մեքենա"), "22 машины")
        // Подпись под числом плитки: число нарисовано отдельно, но
        // читается вместе с ней — «6 машины» глаз ловит как опечатку.
        check("ru: слово под числом 6", Terms.unitWord(6, "մեքենա"), "машин")
        check("ru: слово под числом 1", Terms.unitWord(1, "մեքենա"), "машина")
        check("ru: слово под числом 2", Terms.unitWord(2, "մեքենա"), "машины")
        check("ru: исполнитель", Terms.staff(3, "Լվացող"), "3 мойщика")
        check("ru: один исполнитель", Terms.staff(1, "Լվացող"), "1 мойщик")
        check("ru: номер клиента", Terms.clientId("Պետհամարանիշ"), "Госномер")

        // Слово могло приехать с сервера уже переведённым — обратный
        // поиск обязан найти его формы, иначе «машина» застряла бы
        // навсегда при переключении на английский.
        check("ru: узнаёт своё же слово", Terms.units(5, "машина"), "5 машин")

        // ── английский ──
        LangStore.testOnlySet(.en)
        check("en: единица", Terms.unit("մեքենա").nom, "car")
        check("en: 1", Terms.units(1, "մեքենա"), "1 car")
        check("en: 0", Terms.units(0, "մեքենա"), "0 cars")
        check("en: из русского в английский", Terms.unit("машина").nom, "car")
        check("en: исполнитель", Terms.staff(2, "Լվացող"), "2 washers")

        // ── слово владельца не трогаем ни на одном языке ──
        for lang in Lang.allCases {
            LangStore.testOnlySet(lang)
            check("\(lang.rawValue): своё слово цело", Terms.unit("Тачка").nom, "Тачка")
            check("\(lang.rawValue): своё слово с числом", Terms.units(5, "Тачка"), "5 Тачка")
        }

        print(failed == 0 ? "\nслова ниши: все проверки пройдены\n"
                          : "\nслова ниши: \(failed) провалено\n")
        return failed
    }
}
#endif
