/**
 * Тестовый стенд: одно место, которое знает, что это не бой.
 *
 * Стенд собирается тем же образом и с тем же `NODE_ENV=production`, что
 * и боевой сайт, и это не экономия: стенд, собранный иначе, проверяет не
 * то приложение, которое поедет к клиентам. Отличие ровно одно, и оно
 * снаружи — переменная `STAGING`.
 *
 * От неё зависят три вещи, и все три про то, чтобы стенд нельзя было
 * перепутать с боем:
 *
 *   1. код подтверждения печатается в лог вместо отправки SMS
 *      (см. `lib/sms.ts`) — иначе каждая проверка входа стоит денег с
 *      того же баланса, что и боевые регистрации;
 *   2. поисковики получают запрет на индексацию (см. `app/robots.ts`) —
 *      иначе стенд встаёт в выдачу рядом с боевым сайтом и уводит с
 *      него людей;
 *   3. в интерфейсе висит метка, которую видно на каждом экране.
 *
 * Третье выглядит косметикой, но именно оно защищает первые два.
 * `STAGING` можно занести в боевое окружение по ошибке — скопировали
 * `.env`, перепутали каталог. Такая ошибка тихая: сайт продолжает
 * работать, а вход по SMS ломается для всех сразу, и понять это можно
 * только по жалобам. С меткой ошибка перестаёт быть тихой: на боевом
 * домене появляется полоса «ТЕСТ», и это замечают в первую минуту.
 *
 * Вторая половина защиты живёт в `infra/deploy.sh`: боевой деплой
 * отказывается стартовать, если увидит `STAGING` в своём `.env`.
 */
import { env } from './env';

/**
 * Стенд ли это.
 *
 * Признаётся только `1`. Ни `true`, ни `yes`, ни имя окружения: у
 * переменной, которая переключает поведение боевого сайта, не должно
 * быть нескольких написаний. Иначе однажды кто-то напишет `STAGING=0`,
 * ожидая «выключено», и получит непустую строку.
 */
export function isStaging(): boolean {
  return env('STAGING') === '1';
}

/**
 * Как стенд называется в интерфейсе.
 *
 * По умолчанию просто «ТЕСТ». Переменная нужна, когда стендов станет
 * больше одного и надо различать, на каком именно вы находитесь.
 */
export function stagingLabel(): string {
  return env('STAGING_LABEL') ?? 'ТЕСТ';
}
