import { cache } from 'react';
import { and, count, eq } from 'drizzle-orm';
import { db } from './db';
import { orders, services, users } from './db/schema';
import type { Membership, Tenant } from './db/schema';
import { NICHES, type NicheKey } from './niches';

/**
 * Начало работы.
 *
 * Не тур по разделам и не мастер из четырнадцати экранов, а ответ на
 * один вопрос первого дня: **что мне сделать прямо сейчас**. Продукт
 * приходит настроенным — при регистрации бизнес получает свои услуги,
 * термины и роль исполнителя, — поэтому объяснять здесь нечего, кроме
 * следующего шага.
 *
 * ГЛАВНОЕ РЕШЕНИЕ: шаги считаются по ДАННЫМ бизнеса, а не по нажатиям.
 *
 * Флаг «шаг выполнен» разъезжается с правдой на первом же событии,
 * которого он не видел: услугу завели из приложения, мойщика добавили
 * до того, как владелец открыл список, базу восстановили из выгрузки.
 * После этого продукт просит добавить услуги того, у кого их двадцать, —
 * и человек перестаёт верить не чек-листу, а продукту. Поэтому здесь
 * хранится ровно одна дата на человека (`users.setup_hidden_at`) — та,
 * которой нет в данных: «я это убрал».
 *
 * Шагов четыре, и все четыре — минимум до первой настоящей операции.
 * Клиентов, расходов, зарплатных правил и отчётов здесь нет намеренно:
 * до первой машины они не нужны ни одному владельцу, а список из
 * девяти дел не начинают вовсе.
 */

/**
 * Сколько машин считается «бизнес уже работает».
 *
 * После этого числа блок не показывается никогда — и не важно, дошли ли
 * руки до всех шагов. Десять записей это не «попробовал», а рабочая
 * неделя маленькой мойки; человек, который её отработал, продукт уже
 * освоил, и «начало работы» на его главной говорит только о том, что
 * продукт не заметил самого главного.
 *
 * Шаг с ценами при этом остаётся невыполненным честно: заводские цены
 * так и не тронуты. Просто сказать об этом первым экраном — не дело
 * онбординга, у которого начало давно позади.
 */
const SETTLED_ORDERS = 10;

export type SetupStepKey = 'business' | 'services' | 'staff' | 'firstOrder';

export type SetupStep = {
  key: SetupStepKey;
  done: boolean;
  /** куда ведёт действие шага — настоящий раздел продукта, не мастер */
  href: string;
};

export type Setup = {
  steps: SetupStep[];
  done: number;
  total: number;
  /** первый невыполненный — единственное, что подсвечивается в меню */
  next: SetupStep | null;
  complete: boolean;
  /** показывать ли блок на главной */
  visible: boolean;
  /** сколько машин записано за всё время */
  orders: number;
};

/**
 * Три числа, по которым видно состояние бизнеса.
 *
 * `cache` — не оптимизация, а требование правды: блок настройки
 * считает раскладка кабинета (ради точки в меню) и сама главная (ради
 * списка шагов). Два независимых чтения в одном запросе могли бы
 * разойтись, и меню подсветило бы шаг, которого на странице уже нет.
 * Ключ — идентификатор бизнеса, потому что объекты тенанта у этих двух
 * вызывающих разные.
 */
const readFacts = cache(async (tenantId: string) => {
  const [priced, staff, made] = await Promise.all([
    db
      .select({ name: services.name, price: services.price })
      .from(services)
      .where(and(eq(services.tenantId, tenantId), eq(services.active, true))),
    db
      .select({ n: count() })
      .from(users)
      .where(
        and(eq(users.tenantId, tenantId), eq(users.role, 'staff'), eq(users.active, true)),
      ),
    /* Отменённые записи считаются тоже. Шаг спрашивает «умеет ли эта
       мойка записывать машины», а не «сколько она заработала»: человек,
       записавший первую машину и тут же её отменивший, ответил на этот
       вопрос — и увидеть после этого «запишите первую машину» значило бы
       получить от продукта отрицание того, что только что сделал. */
    db.select({ n: count() }).from(orders).where(eq(orders.tenantId, tenantId)),
  ]);

  return {
    services: priced,
    staff: staff[0]?.n ?? 0,
    orders: made[0]?.n ?? 0,
  };
});

/**
 * Тронут ли прейскурант.
 *
 * Услуги новому бизнесу заводит регистрация — из конфига ниши, с
 * заводскими ценами (см. lib/tenant.ts). Считать этот шаг выполненным
 * только потому, что строки в таблице есть, значит соврать: цены в нём
 * не мойки, а наши, и первая же машина запишется не за те деньги.
 *
 * Поэтому шаг спрашивает не «есть ли услуги», а «свои ли они»: список
 * отличается от заводского названием, ценой или длиной. Любое из трёх
 * означает, что владелец в прейскурант заходил и он теперь его.
 *
 * Ниша, которой нет в конфиге, считается тронутой: сравнивать не с чем,
 * а просить человека проверить цены, которые мы не заводили, незачем.
 */
function pricesAreOwn(niche: string, rows: { name: string; price: number }[]): boolean {
  const factory = NICHES[niche as NicheKey]?.services;
  if (!factory) return true;
  if (rows.length !== factory.length) return true;

  const priceOf = new Map(factory.map((s) => [s.name, s.price]));
  return rows.some((r) => priceOf.get(r.name) !== r.price);
}

/**
 * Состояние настройки для владельца.
 *
 * Считается на каждой странице кабинета, но стоит дёшево: три
 * подсчёта по индексам, и те — один раз на запрос. Тому, кто блок уже
 * убрал, не стоит и этого: выходим до единого обращения к базе.
 */
export async function getSetup(
  tenant: Tenant,
  me: Membership,
  /**
   * Считать так, будто блок не убирали.
   *
   * Нужно ровно одному месту — предложению вернуть настройку на своей
   * странице. Оно обязано знать не «показывается ли блок сейчас», а
   * «есть ли смысл его возвращать», и это разные вопросы: у мойки,
   * которая работает третий месяц, возвращать нечего.
   */
  { ignoreHidden = false }: { ignoreHidden?: boolean } = {},
): Promise<Setup> {
  if (me.setupHiddenAt && !ignoreHidden) return hidden();

  const facts = await readFacts(tenant.id);

  const steps: SetupStep[] = [
    /* Бизнес заведён самой регистрацией: название, ниша и владелец у
       него уже есть. Шаг стоит первым и сразу выполненным нарочно —
       список начинается не с нуля, и первое, что человек узнаёт про
       свою настройку, это что часть её уже сделана за него. */
    { key: 'business', done: true, href: '/owner/settings' },
    { key: 'services', done: pricesAreOwn(tenant.niche, facts.services), href: '/owner/services' },
    { key: 'staff', done: facts.staff > 0, href: '/owner/staff' },
    /* Последний шаг — не настройка, а первая настоящая работа: ради неё
       три предыдущих и делались. Ведёт на экран смены, а не на выдуманную
       форму: машину записывают там, где её записывают каждый день. */
    { key: 'firstOrder', done: facts.orders > 0, href: '/work' },
  ];

  const done = steps.filter((s) => s.done).length;
  const complete = done === steps.length;

  return {
    steps,
    done,
    total: steps.length,
    next: steps.find((s) => !s.done) ?? null,
    complete,
    visible: facts.orders <= SETTLED_ORDERS,
    orders: facts.orders,
  };
}

/** Состояние «блока нет»: считать по нему нечего и показывать нечего. */
function hidden(): Setup {
  return {
    steps: [],
    done: 0,
    total: 0,
    next: null,
    complete: false,
    visible: false,
    orders: 0,
  };
}

/**
 * Показывать ли приветствие первого входа.
 *
 * Один раз за всю жизнь участия. У тех, кто работает в продукте давно,
 * дата проставлена миграцией — окно «Добро пожаловать» посреди рабочего
 * дня было бы не знакомством, а помехой.
 */
export function needsWelcome(me: Membership): boolean {
  return me.welcomeSeenAt === null;
}
