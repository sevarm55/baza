/**
 * Язык движения Tetrin.
 *
 * До сих пор длительности жили в двух местах: `--t-micro`/`--t-press` в
 * `globals.css` и рукописные `0.18` в свифте с котлином. Пока их три
 * набора, «одинаково на всех экранах» проверить нечем, и веб уезжает от
 * приложения на полкадра в каждом переходе.
 *
 * Здесь один набор для веба; те же числа продублированы в
 * `ios/Tetr/Design/Motion.swift` и `android/.../design/Motion.kt` с
 * комментарием-ссылкой сюда. Значения выбраны так, чтобы каждое имело
 * свою работу: `instant` для того, что должно успеть под пальцем,
 * `fast` для смены состояния кнопки, `normal` для появления содержимого,
 * `slow` для перестроения фигуры.
 *
 * Секунды, а не миллисекунды: `motion/react` считает в секундах, и
 * пересчёт в каждом вызове — лишний повод ошибиться на порядок.
 */

export const T = {
  /** нажатие, отклик под пальцем */
  instant: 0.11,
  /** смена состояния мелкой детали */
  fast: 0.17,
  /** появление содержимого, перекрёстное затухание */
  normal: 0.24,
  /** перестроение фигуры, морф */
  slow: 0.45,
  /** полный оборот фирменного загрузчика */
  loader: 1.35,
} as const;

/** Кривые. Те же, что в `--ease` и `--slow`. */
export const E = {
  /** резкий выход, мягкое гашение */
  standard: [0.2, 0, 0, 1],
  /** длинный выкат для морфа */
  soft: [0.16, 1, 0.3, 1],
  /** пружина с еле заметным перелётом */
  spring: [0.34, 1.28, 0.64, 1],
} as const;

/**
 * Пружины для `motion/react`.
 *
 * `springSoft` возит крупное: лист, окно, перестроение фигуры.
 * `springSnap` возит мелкое: галочку, значок, отметку выбора.
 */
export const SPRING = {
  soft: { type: 'spring', stiffness: 260, damping: 28, mass: 0.9 },
  snap: { type: 'spring', stiffness: 340, damping: 24, mass: 0.7 },
} as const;

/**
 * Сколько ждать, прежде чем показать, что идёт загрузка.
 *
 * Запрос на 90 мс, отмеченный скелетом, выглядит хуже, чем запрос на
 * 90 мс без ничего: человек видит вспышку серых прямоугольников и
 * считает, что страница дрогнула. Порог берём по нижней границе того,
 * что вообще воспринимается как задержка.
 *
 * Готовый ответ при этом никогда не придерживаем: порог откладывает
 * показ загрузки, а не показ данных.
 */
export const LOADING_DELAY = 180;

/**
 * Сколько держать отметку «получилось».
 *
 * Достаточно, чтобы поймать глазом, и мало, чтобы не превратиться в
 * состояние, из которого надо выходить.
 */
export const SUCCESS_HOLD = 1400;

/**
 * После какой задержки объяснять, что происходит.
 *
 * Кнопка, которая молчит «Сохраняем…» шесть секунд, читается как
 * зависшая. На этом пороге появляется вторая строка про то, чем
 * приложение занято, но никогда не появляется процент: сервер его не
 * присылает, а нарисованный процент врёт.
 */
export const LONG_WAIT = 5000;
