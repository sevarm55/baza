/**
 * Чтение переменных окружения.
 *
 * Одна строчка ради одной ошибки, которая стоила боевой регистрации.
 *
 * В `docker-compose.yml` необязательные переменные записываются как
 * `SMS_AUTH_SCHEME: ${SMS_AUTH_SCHEME:-}` — и если её не задали, в
 * контейнер приезжает НЕ отсутствующая переменная, а пустая строка. А в
 * коде стояло `process.env.SMS_AUTH_SCHEME ?? 'Bearer'`, и `??`
 * подставляет запасное значение только для `null` и `undefined`: пустая
 * строка для него — нормальное значение.
 *
 * В итоге заголовок уходил как `Authorization:  <токен>`, без слова
 * `Bearer`. Оператор отвечал 401, токен при этом был совершенно
 * исправен, и найти это по логам было нечем: в них видно «401», а не
 * «мы забыли слово».
 *
 * Отсюда правило: пустая строка в окружении означает «не задано». Иначе
 * между `docker-compose.yml` и `??` в коде остаётся зазор, в который эта
 * ошибка возвращается каждый раз, когда добавляют новую необязательную
 * переменную.
 */
export function env(name: string): string | undefined {
  const value = process.env[name];
  return value === undefined || value === '' ? undefined : value;
}
