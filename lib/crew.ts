import { staffShare } from './money';

/**
 * Совместная мойка: одна машина, несколько исполнителей.
 *
 * Здесь только арифметика — ни базы, ни запросов. Причина та же, что у
 * `priceForTier`: считать деньги обязано одно место. Сервер делит фонд
 * при записи, экран мойщика показывает будущую долю до нажатия кнопки,
 * кабинет владельца объясняет уже посчитанное. Три ответа на один
 * вопрос, и разойтись им негде только пока формула одна.
 *
 * ПРАВИЛО ЦЕЛИКОМ:
 *
 *   моет один   → фонд = цена × ЛИЧНЫЙ процент этого человека;
 *   моют двое+  → фонд = цена × ОБЩИЙ процент команды, делится поровну.
 *
 * Общий процент — это не «по столько каждому». Пятьдесят процентов на
 * троих означают пять тысяч с десятитысячной машины на всех, а не
 * пятнадцать. Иначе зарплатный фонд одной машины перевалил бы за её
 * цену на четвёртом участнике.
 */

/** Сколько человек максимум может мыть одну машину. */
export const MAX_CREW = 8;

/**
 * Зарплатный фонд машины.
 *
 * Округление вниз — то же самое `staffShare`, которым продукт считает
 * долю одиночного мойщика с самого начала. Второй способ округлять
 * означал бы, что совместная мойка на одного человека даёт не ту сумму,
 * что одиночная, при одинаковом проценте.
 */
export function crewPool(price: number, percent: number): number {
  return staffShare(price, percent);
}

/**
 * Разделить фонд между участниками.
 *
 * ОСТАТОК НЕ ТЕРЯЕТСЯ И НЕ ПРИДУМЫВАЕТСЯ. Пять тысяч на троих — это не
 * «по 1 666,67»: денег в драмах дробных не бывает, а сумма долей обязана
 * до последней единицы совпасть с фондом. Иначе зарплатная ведомость не
 * сходится с расходом на зарплату, и расхождение всплывает у владельца
 * ровно там, где продукт обещал порядок.
 *
 * Поэтому 5 000 на троих дают 1 667 + 1 667 + 1 666. Лишние единицы
 * уходят первым по порядку, а первый — автор записи: если уж кому-то
 * достаётся на драм больше, пусть это будет тот, кто взял на себя
 * оформление.
 *
 * Пустой список — пустой ответ: фонд, который некому раздать, не бывает.
 */
export function splitPool(pool: number, people: number): number[] {
  if (people <= 0) return [];
  const base = Math.floor(pool / people);
  const extra = pool - base * people;
  return Array.from({ length: people }, (_, i) => base + (i < extra ? 1 : 0));
}

/**
 * Сколько получит каждый и по какой ставке — всё, что нужно и серверу,
 * и обоим экранам.
 *
 * `percent` возвращается наружу, потому что он и есть то, что уйдёт
 * снимком в запись: спрашивать «а какой процент применился» второй раз
 * было бы вторым источником правды для той же величины.
 */
export function crewSplit(params: {
  price: number;
  /** сколько человек мыли, считая автора записи */
  people: number;
  /** личная ставка того, кто моет один */
  soloPercent: number;
  /** общая ставка команды; null — совместная мойка не настроена */
  teamPercent: number | null;
}): { percent: number; pool: number; shares: number[] } {
  const percent =
    params.people > 1 ? (params.teamPercent ?? 0) : params.soloPercent;
  const pool = crewPool(params.price, percent);
  return { percent, pool, shares: splitPool(pool, params.people) };
}

/**
 * Список участников без повторов, автор первым.
 *
 * Автора добавляем сами и не спрашиваем. Мойщик, включивший «помыли
 * вместе», отмечает КОЛЛЕГ — искать себя в списке и ставить себе галочку
 * он не должен, а забыв её поставить, остался бы без денег за
 * собственную работу. Повтор себя же в присланном списке при этом не
 * ошибка, а обычное дело для клиента, который решил прислать состав
 * целиком, — поэтому он молча схлопывается, а не отвергается.
 */
export function crewOf(authorId: string, others: readonly string[] = []): string[] {
  const seen = new Set<string>([authorId]);
  const out = [authorId];
  for (const id of others) {
    const clean = String(id ?? '').trim();
    if (!clean || seen.has(clean)) continue;
    seen.add(clean);
    out.push(clean);
  }
  return out;
}
