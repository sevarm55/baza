/**
 * Автофокус — только на компьютере.
 *
 * На телефоне поле, поймавшее фокус при открытии листа, поднимает
 * клавиатуру раньше, чем человек успел прочитать, о чём его спрашивают:
 * половина листа уезжает под клавиатуру, и первое, что приходится
 * сделать, — закрыть её, чтобы увидеть остальные поля. На компьютере
 * фокус наоборот экономит касание: клавиатура там всегда открыта.
 *
 * Проверка идёт в момент отрисовки, а не хуком по ширине окна:
 * `autoFocus` React применяет ровно один раз, когда вставляет узел в
 * страницу, и решение нужно принять к этому мгновению. Формы, которые
 * этим пользуются, живут в листах и открываются нажатием, то есть уже
 * в браузере; на сервере функция честно отвечает «нет», и тогда фокус
 * не ставится вовсе — это лучше, чем поставить его на телефоне.
 */
export function autoFocusOnDesktop(): boolean {
  if (typeof window === 'undefined') return false;
  return !window.matchMedia('(max-width: 767px)').matches;
}
