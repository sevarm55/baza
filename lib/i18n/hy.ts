/**
 * «С одной машины», «с одного заказа» — единица учёта в отделительном
 * падеже.
 *
 * Раньше под итогом стояло просто «մեկից» — «с одной». С чего именно
 * одной, страница не говорила, хотя знает: у каждого бизнеса своя
 * единица учёта, у мойки это машина, у барбершопа клиент. Вписать
 * «մեքենա» в общий словарь нельзя — он один на все ниши.
 *
 * Падеж строится по правилу армянского: после гласной окончание `-յից`,
 * после согласной `-ից`. Этого хватает на все шесть единиц продукта:
 * մեքենա → մեքենայից, պատվեր → պատվերից, ընդունելություն →
 * ընդունելությունից, հաճախորդ → հաճախորդից, այց → այցից.
 */
export function fromOneUnit(unit: string): string {
  const vowels = 'աեէըիոօու';
  const last = unit.trim().slice(-1);
  return `մեկ ${unit}${vowels.includes(last) ? 'յից' : 'ից'}`;
}
