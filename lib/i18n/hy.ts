/**
 * Форма словаря.
 *
 * `as const` выше стоит ради читаемости самого файла, но снаружи он не
 * нужен: с ним каждая строка получила бы СВОЙ тип («Փոխել», а не
 * string), и русский файл не прошёл бы проверку ни одной строкой. Здесь
 * литералы расширяются обратно до string, а форма — вложенность, массивы
 * и сигнатуры функций — сохраняется целиком.
 *
 * Из-за этого ru.ts и en.ts обязаны повторить структуру армянского до
 * последнего ключа: пропущенный ключ или лишний аргумент функции — это
 * ошибка сборки, а не пустое место на экране у пользователя.
 */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends (...args: infer A) => infer R
      ? (...args: A) => R
      : T extends readonly (infer E)[]
        ? readonly Widen<E>[]
        : { -readonly [K in keyof T]: Widen<T[K]> };

export type Dict = Widen<typeof hy>;
