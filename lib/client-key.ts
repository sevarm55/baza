/**
 * Единое имя клиента для записи, поиска, абонемента и истории.
 *
 * Армянский номер машины люди набирают как `77GG477`, `77 GG 477` или
 * `77-GG-477`. Это один автомобиль, и вид у него должен быть один:
 * слитный, без пробелов и дефисов, в верхнем регистре.
 *
 * Красивая форма с пробелами тут была и оказалась хуже. Номер на
 * пластине написан слитно, мойщик набирает его слитно, а продукт
 * показывал его иначе, чем человек ввёл, — и в списке из сорока строк
 * глаз спотыкался о собственную же машину. Плюс два вида в базе
 * означали два вида в поиске: половина карточек не открывалась вовсе.
 *
 * Одна форма снимает оба вопроса разом: как ввёл, так и лежит, так и
 * ищется.
 */
export function normalizeClientKey(raw: string): string {
  return compactClientKey(raw);
}

/**
 * Номер, приехавший куском адреса.
 *
 * `decodeURIComponent` бросает на кривом проценте — «%E0%A4%A» это не
 * ошибка ввода, а обрезанная ссылка, и падать на ней маршрут не должен:
 * наружу это уходило бы пятисоткой. Не разобрали — берём как есть,
 * дальше такой ключ просто не найдётся, и ответом будет честное «нет
 * такого номера».
 */
export function decodeClientKey(raw: string): string {
  try {
    return decodeURIComponent(raw);
  } catch {
    return raw;
  }
}

/**
 * Ключ без пробелов и дефисов — для сравнения, а не для показа.
 *
 * Красивая форма с пробелами появилась не сразу, и в базе остались
 * записи, заведённые слитно: `99FF333` рядом с `88 GG 123`. Поиск по
 * красивой форме их не находил — открытая из ленты машина отвечала 404,
 * причём ровно та, чей ключ записан по-старому.
 *
 * Поэтому сравниваем всегда по слитной форме: она одна и та же у всех
 * трёх написаний, которые набирает человек, и у обеих, которые лежат в
 * базе. Показываем при этом по-прежнему красивую.
 */
export function compactClientKey(raw: string): string {
  return delatinize(stripControls(raw).trim().toUpperCase()).replace(/[\s-]+/g, '');
}

/**
 * Выбросить управляющие символы.
 *
 * Их не набирают руками — они приезжают из сканера номеров, из вставки
 * буфера и из адресной строки, куда кто-то подставил `%00`. Postgres
 * нулевой байт в тексте не принимает вовсе и отвечает ошибкой, а та
 * выходила наружу пятисоткой: карточка клиента по такому адресу
 * сообщала «сервер сломался» вместо «такого номера нет».
 *
 * Выбрасываем, а не отказываем: для человека это невидимый мусор внутри
 * нормального номера, и терять из-за него запись машины не за что.
 */
function stripControls(s: string): string {
  /* Диапазоны заданы кодами намеренно: сами символы в исходнике невидимы,
     и такую строчку нельзя ни прочитать, ни проверить глазами. */
  // eslint-disable-next-line no-control-regex
  return s.replace(/[\u0000-\u001F\u007F-\u009F]/g, '');
}

/**
 * Кириллические двойники латинских букв — в латиницу.
 *
 * На пластине армянского номера буквы латинские, а телефон у мойщика
 * переключён на русскую раскладку: «34АА123» кириллицей и «34AA123»
 * латиницей набираются одинаковыми движениями и выглядят на экране
 * посимвольно одинаково. Для базы это два разных клиента.
 *
 * Ошибка из тех, которые невозможно увидеть глазами: в списке две
 * одинаковые строки, у каждой своя история визитов и своя сумма,
 * «постоянный клиент» не узнаётся при вводе, абонемент не находится, а
 * на вопрос «сколько эта машина у нас оставила» продукт отвечает
 * половиной правды. Единственный способ заметить — сравнить коды
 * символов.
 *
 * Заменяем только те буквы, которые совпадают начертанием. Остальная
 * кириллица (Б, Г, Д, Ж…) двойников не имеет, на пластинах не
 * встречается и остаётся как есть: превращать её во что-то похожее
 * значило бы портить ключ, а не чинить.
 *
 * На телефоны это не влияет: цифры и «+» не трогаем.
 */
const CONFUSABLE: Record<string, string> = {
  А: 'A', В: 'B', Е: 'E', К: 'K', М: 'M', Н: 'H', О: 'O',
  Р: 'P', С: 'C', Т: 'T', У: 'Y', Х: 'X', І: 'I', Ј: 'J',
};

function delatinize(s: string): string {
  let out = '';
  for (const ch of s) out += CONFUSABLE[ch] ?? ch;
  return out;
}
