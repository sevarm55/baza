/**
 * Единое имя клиента для записи, поиска, абонемента и истории.
 *
 * Армянский номер машины люди набирают как `77GG477`, `77 GG 477` или
 * `77-GG-477`. Это один автомобиль, и вид у него должен быть один:
 * слитный, без пробелов и дефисов, в верхнем регистре.
 *
 * Красивая форма с пробелами тут была и оказалась хуже. Номер на
 * пластине написан слитно, мойщик набирает его слитно, а продукт
 * показывал его иначе, чем человек ввёл, — и в списке из сорока строк
 * глаз спотыкался о собственную же машину. Плюс два вида в базе
 * означали два вида в поиске: половина карточек не открывалась вовсе.
 *
 * Одна форма снимает оба вопроса разом: как ввёл, так и лежит, так и
 * ищется.
 */
export function normalizeClientKey(raw: string): string {
  return compactClientKey(raw);
}

/**
 * Ключ без пробелов и дефисов — для сравнения, а не для показа.
 *
 * Красивая форма с пробелами появилась не сразу, и в базе остались
 * записи, заведённые слитно: `99FF333` рядом с `88 GG 123`. Поиск по
 * красивой форме их не находил — открытая из ленты машина отвечала 404,
 * причём ровно та, чей ключ записан по-старому.
 *
 * Поэтому сравниваем всегда по слитной форме: она одна и та же у всех
 * трёх написаний, которые набирает человек, и у обеих, которые лежат в
 * базе. Показываем при этом по-прежнему красивую.
 */
export function compactClientKey(raw: string): string {
  return raw.trim().toUpperCase().replace(/[\s-]+/g, '');
}
