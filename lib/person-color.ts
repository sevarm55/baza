/**
 * Цвет человека.
 *
 * Один и тот же работник всегда одного цвета — в ленте, в списке на смене,
 * в истории дня. Тогда «кто это помыл» читается по цвету, ещё до того как
 * прочитано имя: на мойке два-три человека, и глаз запоминает их за день.
 *
 * Цвет выводится из имени, а не хранится: не нужно ни поле в базе, ни
 * вопрос при найме, и он одинаков в вебе и в приложении — там ровно та же
 * свёртка по тем же шести оттенкам.
 */
const COUNT = 6;

export function personColor(name: string | null | undefined): string {
  if (!name) return 'var(--muted-foreground)';

  /* Простая устойчивая свёртка. Криптостойкость тут не нужна, нужна
     одинаковость: имя всегда даёт один и тот же цвет. */
  let hash = 0;
  for (const ch of name) {
    hash = (hash * 31 + ch.codePointAt(0)!) & 0xffffff;
  }
  return `var(--person-${hash % COUNT})`;
}
