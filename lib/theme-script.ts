import { createHash } from 'node:crypto';

/**
 * Скрипт, который ставит тему до первой отрисовки.
 *
 * Вынесен из разметки в отдельный модуль ради одной строки ниже — его
 * хеша. Разберём, почему не проще.
 *
 * Скрипт обязан быть встроенным: он должен отработать ДО того, как
 * браузер нарисует первый кадр, иначе экран моргнёт чужим цветом, и на
 * телефоне это очень заметно. Внешний файл так не успевает.
 *
 * Встроенный скрипт под строгой политикой содержимого нужно чем-то
 * разрешить. Первым делом напрашивается одноразовый ключ — и это
 * ловушка: React НЕ восстанавливает атрибут `nonce` при гидратации.
 * Сервер отдаёт `nonce="…"`, клиент видит `nonce=""`, деревья
 * расходятся, гидратация обрывается — и страница остаётся картинкой.
 * Ни одна кнопка не работает, в консоли одна строка про «attributes …
 * didn't match», и связать её с окном входа, которое перестало
 * открываться, получается далеко не сразу.
 *
 * Поэтому здесь хеш. Скрипт статический, его содержимое известно на
 * сборке, и `sha256-…` в `script-src` разрешает ровно его и ничего
 * больше. `strict-dynamic` хеши не отменяет — он отменяет списки
 * адресов, а ключи и хеши продолжают работать.
 *
 * Правка текста скрипта автоматически меняет хеш: разойтись они не
 * могут по построению.
 */
export const THEME_SCRIPT =
  `(()=>{try{document.documentElement.dataset.theme=localStorage.getItem('bazis.theme')==='light'?'light':'dark'}catch(e){}})();`;

/** `sha256-…` для `script-src`. Считается один раз при загрузке модуля. */
export const THEME_SCRIPT_HASH = `'sha256-${createHash('sha256')
  .update(THEME_SCRIPT)
  .digest('base64')}'`;
