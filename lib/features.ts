/**
 * Абонементы, которые бизнес продаёт своим клиентам: «10 моек по цене 8».
 *
 * Механика денег в них нетривиальная — выручка возникает при продаже,
 * а списание её не создаёт, — и продумать её стоит спокойно, а не
 * впопыхах перед первым показом. До тех пор скрыто.
 *
 * Уже проданные абонементы никуда не деваются: данные лежат в базе
 * и оживут вместе с флагом.
 */
export function passesEnabled(): boolean {
  return process.env.PASSES_ENABLED === '1';
}
