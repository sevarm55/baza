/**
 * Части продукта, которые можно временно убрать с глаз.
 *
 * Не удаляем код, а прячем: схема, запросы и тесты остаются на месте,
 * возврат стоит одну переменную. Удалённую фичу пришлось бы писать
 * заново, а спрятанная просто ждёт своего часа.
 */

/**
 * Абонементы, которые бизнес продаёт своим клиентам: «10 моек по цене 8».
 *
 * Механика денег в них нетривиальная — выручка возникает при продаже,
 * а списание её не создаёт, — и продумать её стоит спокойно, а не
 * впопыхах перед первым показом. До тех пор скрыто.
 *
 * Уже проданные абонементы никуда не деваются: данные лежат в базе
 * и оживут вместе с флагом.
 */
export function passesEnabled(): boolean {
  return process.env.PASSES_ENABLED === '1';
}

/**
 * Адрес приложения в App Store.
 *
 * Переменной, а не строкой в коде, по одной причине: адреса ещё нет.
 * Приложение отправлено на ревью, и числовой идентификатор появляется
 * только вместе с публикацией. Придумать его нельзя — выдуманная ссылка
 * с витрины ведёт в пустоту, и это хуже, чем её отсутствие.
 *
 * Пока переменной нет, витрина показывает знак магазина без ссылки и
 * подписывает его «скоро» — ровно то же, что стоит рядом у Android.
 * Появится адрес — знак станет ссылкой сам, без правки кода.
 *
 * Пустая строка считается «не задана»: в docker-compose незаполненная
 * переменная доезжает до контейнера именно пустой, а не отсутствующей.
 */
export function appStoreUrl(): string | null {
  const url = process.env.APP_STORE_URL?.trim();
  return url ? url : null;
}
